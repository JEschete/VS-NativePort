"""Track the migration of C-style native headers to C++, and keep the retired C linkage from returning.

  python tools\\ledger\\headers.py --sync    rescan the tracked files, follow .h -> .hpp renames, refresh the tracker
  python tools\\ledger\\headers.py --check   exit 1 on a stale ledger, a regressed file or a new C-style file

Docs\\ledgers\\HEADER_LEDGER.csv has a `header` row for every header that was C-style when the ledger was created
(every `.h` and every `.hpp` failing a criterion) and a `source` row for every `.cpp` that had C linkage then.
Docs\\CPP_HEADERS.md defines each criterion and its C++ replacement. All columns except `notes` are measured, and a
row is `done` only when every criterion of its kind holds. `done` is sticky: a later regression fails --check instead
of being re-measured away. Once no source row remains, C linkage is retired: a tracked file that regains it fails
--check even while other criteria keep it remaining. RETIRED_CRITERIA, cleared from every tracked header, are held the
same way. `retired` is written by hand for a file deleted on purpose and
needs a note. Rows are only created when the ledger is first written, so a new C-style file fails --check rather than
joining the ledger.
Tracked in issue #441.
"""
from __future__ import annotations

import argparse
import json
import posixpath
import re
import sys
from collections import Counter
from functools import cached_property
from itertools import pairwise
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gates  # noqa: E402
from gates import PREPROCESSOR_LINE, Issue, read_csv, slash, strip_source  # noqa: E402

SUMMARY_BEGIN = "<!-- headers:begin (generated by tools/ledger/headers.py --sync) -->"
SUMMARY_END = "<!-- headers:end -->"
COUNTS = ["c_linkage", "static_asserts", "typedefs", "void_params", "gnu_attributes", "macros", "global_decls"]
MEASURED = ["generated", "guard", *COUNTS, "c_wrapped", "baseline"]
SOURCE_MEASURED = ["generated", "c_linkage"]
FIELDS = ["id", "kind", "path", "origin", *MEASURED, "status", "notes"]
STATUS_VALUES = {"remaining", "done", "retired"}
HEADER_SUFFIXES = (".h", ".hpp")
SOURCE_SUFFIXES = (".cpp",)
PRAGMA_ONCE = "pragma-once"
# Include roots besides each project's include\ and src\: the Legacy shims (Directory.Build.props VSCopiedCIncludes).
LEGACY_ROOTS = {"Native/Engine", "Native/Content"}

LINKAGE = re.compile(r'\bextern\s*"C"|\b__cplusplus\b')
STATIC_ASSERT = re.compile(r"\b_Static_assert\b")
TYPEDEF = re.compile(r"\btypedef\b")
VOID_PARAMS = re.compile(r"(?:\b(?!(?:return|sizeof|case|else|do)\b)[A-Za-z_]\w*|\))\s*\(\s*void\s*\)")
GNU_ATTRIBUTE = re.compile(r"\b__attribute__\s*\(\(")
DIRECTIVE = re.compile(r"^[ \t]*#[ \t]*(?P<name>\w+)(?P<rest>(?:[^\n]*\\\n)*[^\n]*)", re.M)
GUARD_TEST = re.compile(r"^(?:ifndef\s+(?P<a>\w+)|if\s+!\s*defined\s*\(?\s*(?P<b>\w+)\s*\)?)\s*$")
NEGATED_DEFINED = re.compile(r"!\s*defined\s*\(?\s*(\w+)")
OPERATOR_NAME = re.compile(r"\boperator\s*[^\s(]+")
NAMESPACE_HEAD = re.compile(r"(?:inline\s+)?namespace(?:\s+[\w:]+)?(?:\s*\[\[[^\]]*\]\])?")
LINKAGE_HEAD = re.compile(r'extern\s*""')
# A forward declaration names a type declared elsewhere (its own header, or a third-party library like SDL).
FORWARD_DECLARATION = re.compile(r"(?:struct|class|union)\s+\w+|enum(?:\s+(?:class|struct))?\s+\w+\s*:\s*[\w\s:]+")
SCOPE_TOKEN = re.compile(r"[{};]")
LITERAL = re.compile(r'(?<!\w)(?:u8|u|U|L)?R"(?P<delimiter>[^()\\\s]{0,16})\((?s:.*?)\)(?P=delimiter)"'
                     r'|"(?:[^"\\\n]|\\.)*"|\'(?:[^\'\\\n]|\\.)*\'')
LINKAGE_BLOCK = re.compile(r'\bextern\s*"C"\s*\{')
QUOTED_INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]*"(?P<name>[^"]+)"', re.M)
# Macros that need the preprocessor itself; anything a constexpr, inline function or template can do is not here.
PERMITTED_MACROS = {
    "VS_ASSERT": "stringizes the asserted condition",
}
# Criteria cleared from every tracked header, each with its C++ form. A header still remaining for other criteria must
# not regain one, which a stale-ledger finding alone would let a sync record.
RETIRED_CRITERIA = {
    "static_asserts": "static_assert",
    "typedefs": "struct X { ... }; or using N = T;",
    "void_params": "f()",
    "gnu_attributes": "a standard attribute",
}


class HeaderWorkspace(gates.Workspace):
    def __init__(self, root: Path = gates.ROOT) -> None:
        super().__init__(root)
        self.ledger = self.root / "Docs" / "ledgers" / "HEADER_LEDGER.csv"
        self.tracker = self.root / "Docs" / "CPP_HEADERS.md"


def kind_of(path: str) -> str:
    return "header" if path.endswith(HEADER_SUFFIXES) else "source"


def guard_of(directives: list[tuple[str, str]], code: str) -> str:
    """`split` for the generator's types-only sections, `macro` for an #ifndef guard, else pragma-once or none."""
    if "VS_TYPES_ONLY" in code:
        return "split"
    for (name, rest), following in pairwise(directives):
        if name == "pragma":
            continue
        test = GUARD_TEST.match(f"{name} {rest.strip()}")
        if test and following[0] == "define" and following[1].split()[:1] == [test.group("a") or test.group("b")]:
            return "macro"
        break
    once = any(name == "pragma" and rest.strip() == "once" for name, rest in directives)
    return PRAGMA_ONCE if once else "none"


def macro_count(directives: list[tuple[str, str]]) -> int:
    """#define directives other than include guards, the generator's section guards and PERMITTED_MACROS."""
    tested: set[str] = set()
    count = 0
    for name, rest in directives:
        if name == "ifndef":
            tested.update(rest.split()[:1])
        elif name in {"if", "elif"}:
            tested.update(NEGATED_DEFINED.findall(rest))
        elif name == "define":
            words = rest.split()
            macro = re.match(r"\w+", rest.strip())
            guard = len(words) == 1 and words[0] in tested
            if not guard and not (macro and macro.group() in PERMITTED_MACROS):
                count += 1
    return count


def global_declarations(code: str) -> int:
    """Declarations at global namespace scope, counting `extern "C"` blocks as global.

    static_assert and forward declarations are not counted: a forward declaration follows the header that defines
    the type, which is measured itself."""
    code = PREPROCESSOR_LINE.sub(" ", code)
    frames: list[str] = []
    pending = ""
    last = 0
    count = 0
    for token in SCOPE_TOKEN.finditer(code):
        symbol = token.group()
        segment = code[last:token.start()]
        last = token.end()
        if "body" in frames:
            if symbol == "{":
                frames.append("body")
            elif symbol == "}":
                frames.pop()
                if "body" not in frames:
                    head = pending
                    declarator = OPERATOR_NAME.sub("operator", head.split("(")[0])
                    function = "(" in head and "=" not in declarator and not re.match(
                        r"(?:typedef\s+)?(?:struct|class|union|enum)\b", head)
                    if function:
                        count += "namespace" not in frames
                        pending = ""
                    else:
                        pending = f"{head} {{}}"
            continue
        head = f"{pending} {segment}".strip()
        global_scope = "namespace" not in frames
        if symbol == ";":
            if (global_scope and head and not head.startswith(("static_assert", "_Static_assert"))
                    and not FORWARD_DECLARATION.fullmatch(head)):
                count += 1
            pending = ""
        elif symbol == "{":
            if NAMESPACE_HEAD.fullmatch(head):
                frames.append("namespace")
                pending = ""
            elif LINKAGE_HEAD.fullmatch(head):
                frames.append("linkage")
                pending = ""
            else:
                frames.append("body")
                pending = head
        elif frames:
            frames.pop()
            pending = ""
    return count


def wrapped_includes(text: str) -> list[str]:
    """Quoted #include names inside `extern "C" { ... }` blocks; nested blocks are counted once."""
    source = strip_source(text, keep_strings=True)
    braces = LITERAL.sub(lambda match: re.sub(r"[^\n]", " ", match.group()), source)
    names: list[str] = []
    end = -1
    for block in LINKAGE_BLOCK.finditer(source):
        if block.start() < end:
            continue
        depth = 0
        end = len(braces)
        for position in range(block.end() - 1, len(braces)):
            if braces[position] == "{":
                depth += 1
            elif braces[position] == "}":
                depth -= 1
                if depth == 0:
                    end = position
                    break
        names += [match.group("name") for match in QUOTED_INCLUDE.finditer(source, block.end(), end)]
    return names


def measure(text: str) -> dict[str, str]:
    comments_removed = strip_source(text, keep_strings=True)
    code = strip_source(text)
    directives = [(match.group("name"), match.group("rest")) for match in DIRECTIVE.finditer(code)]
    values = {
        "guard": guard_of(directives, code),
        "c_linkage": len(LINKAGE.findall(comments_removed)),
        "static_asserts": len(STATIC_ASSERT.findall(code)),
        "typedefs": len(TYPEDEF.findall(code)),
        "void_params": len(VOID_PARAMS.findall(PREPROCESSOR_LINE.sub(" ", code))),
        "gnu_attributes": len(GNU_ATTRIBUTE.findall(code)),
        "macros": macro_count(directives),
        "global_decls": global_declarations(code),
    }
    return {key: str(value) for key, value in values.items()}


def failures(path: str, values: dict[str, str]) -> list[str]:
    """Criteria the file does not yet meet (Docs/CPP_HEADERS.md); a source only has to lose its C linkage."""
    if kind_of(path) == "source":
        return ["c_linkage"] if values["c_linkage"] != "0" else []
    found = [] if path.endswith(".hpp") else ["extension"]
    if values["generated"] == "yes":
        found.append("generated")
    if values["guard"] != PRAGMA_ONCE:
        found.append("guard")
    found += [column for column in [*COUNTS, "c_wrapped", "baseline"] if values[column] != "0"]
    return found


def c_style(path: str, values: dict[str, str]) -> bool:
    """Whether a file outside the ledger is still C-style; quality-baseline debt alone does not make it so."""
    return any(item != "baseline" for item in failures(path, values))


class Scanner:
    def __init__(self, workspace: HeaderWorkspace) -> None:
        self.workspace = workspace
        self.manifest = {slash(path) for path in json.loads(workspace.manifest.read_text(encoding="utf-8"))}
        self.debt: Counter[str] = Counter()
        if workspace.baseline.is_file():
            for item in json.loads(workspace.baseline.read_text(encoding="utf-8"))["findings"]:
                self.debt[slash(item["path"])] += int(item["count"])

    def files(self, suffixes: tuple[str, ...]) -> list[str]:
        root = self.workspace.root
        return sorted(slash(str(path.relative_to(root))) for path in self.workspace.native.rglob("*")
                      if path.suffix in suffixes and path.is_file())

    def headers(self) -> list[str]:
        return self.files(HEADER_SUFFIXES)

    def sources(self) -> list[str]:
        return self.files(SOURCE_SUFFIXES)

    def exists(self, path: str) -> bool:
        return (self.workspace.root / path).is_file()

    def text(self, path: str) -> str:
        """Source text with LF endings, so a checkout's line-ending setting cannot change a measurement."""
        return (self.workspace.root / path).read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n")

    def resolve(self, includer: str, name: str, headers: set[str]) -> str | None:
        """The header a quoted include names: the includer's directory first, then the include roots."""
        local = posixpath.normpath(posixpath.join(posixpath.dirname(includer), name))
        if local in headers:
            return local
        roots = [path for path in headers if path.endswith(f"/{name}")
                 and (posixpath.basename(path[:-len(name) - 1]) in {"include", "src"}
                      or path[:-len(name) - 1] in LEGACY_ROOTS)]
        project = [path for path in roots if path.split("/")[1] == includer.split("/")[1]]
        found = project or roots
        return found[0] if len(found) == 1 else None

    @cached_property
    def wrapped(self) -> Counter[str]:
        """How many `extern "C"` blocks across Native include each header."""
        headers = set(self.headers())
        found: Counter[str] = Counter()
        for path in self.files((*HEADER_SUFFIXES, *SOURCE_SUFFIXES)):
            for name in wrapped_includes(self.text(path)):
                target = self.resolve(path, name, headers)
                if target:
                    found[target] += 1
        return found

    def values(self, path: str) -> dict[str, str]:
        generated = "yes" if path in self.manifest else "no"
        text = self.text(path)
        if kind_of(path) == "source":
            blank = dict.fromkeys(MEASURED, "")
            linkage = len(LINKAGE.findall(strip_source(text, keep_strings=True)))
            return {**blank, "generated": generated, "c_linkage": str(linkage)}
        return {"generated": generated, **measure(text), "c_wrapped": str(self.wrapped[path]),
                "baseline": str(self.debt[path])}


def origin_of(path: str, manifest: set[str]) -> str:
    if path in manifest:
        return "generated"
    return "legacy" if "/Legacy/" in path else "owned"


def renamed(path: str, scanner: Scanner, claimed: set[str]) -> str:
    """A tracked .h that became its sibling .hpp keeps its row."""
    if scanner.exists(path) or not path.endswith(".h"):
        return path
    target = f"{path}pp"
    return target if scanner.exists(target) and target not in claimed else path


def measured_row(row: dict[str, str], scanner: Scanner) -> dict[str, str]:
    if row["status"] == "retired" or not scanner.exists(row["path"]):
        return dict(row)
    values = scanner.values(row["path"])
    status = "done" if row["status"] == "done" or not failures(row["path"], values) else "remaining"
    return {**row, **values, "status": status}


def initial_rows(scanner: Scanner) -> list[dict[str, str]]:
    rows = []
    for prefix, paths in (("H", scanner.headers()), ("S", scanner.sources())):
        tracked = []
        for path in paths:
            values = scanner.values(path)
            if path.endswith(".h") or c_style(path, values):
                tracked.append({"id": "", "kind": kind_of(path), "path": path,
                                "origin": origin_of(path, scanner.manifest), **values, "status": "remaining",
                                "notes": ""})
        for number, row in enumerate(tracked, 1):
            row["id"] = f"{prefix}{number:04d}"
            row["status"] = "remaining" if failures(row["path"], row) else "done"
        rows += tracked
    return rows


def sync(workspace: HeaderWorkspace) -> None:
    scanner = Scanner(workspace)
    previous = read_csv(workspace.ledger)
    if not previous:
        rows = initial_rows(scanner)
    else:
        claimed = {row["path"] for row in previous}
        rows = []
        for row in previous:
            path = renamed(row["path"], scanner, claimed) if row["kind"] == "header" else row["path"]
            claimed.add(path)
            rows.append(measured_row({**row, "path": path}, scanner))
    write_ledger(workspace, rows)
    write_tracker(workspace, rows)


def write_ledger(workspace: HeaderWorkspace, rows: list[dict[str, str]]) -> None:
    terminator = gates.csv_line_terminator(workspace.ledger) if workspace.ledger.is_file() else "\n"
    gates.write_rows(workspace.ledger, [FIELDS, *[[row[name] for name in FIELDS] for row in rows]], terminator)


def summary(rows: list[dict[str, str]]) -> str:
    headers = [row for row in rows if row["kind"] == "header"]
    sources = [row for row in rows if row["kind"] == "source"]
    active = [row for row in headers if row["status"] != "retired"]
    linked = [row for row in sources if row["status"] != "retired"]
    header_status = Counter(row["status"] for row in headers)
    source_status = Counter(row["status"] for row in sources)
    lines = [
        f"**{header_status['done']:,} of {len(headers):,} headers done**, {header_status['remaining']:,} remaining, "
        f"{header_status['retired']:,} retired. **{source_status['done']:,} of {len(sources):,} sources free of "
        f"C linkage**, {source_status['remaining']:,} remaining, {source_status['retired']:,} retired.",
        "",
        "| Header origin | Headers | Done | Remaining | Retired |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for origin in ("generated", "owned", "legacy"):
        members = [row for row in headers if row["origin"] == origin]
        counts = Counter(row["status"] for row in members)
        lines.append(f"| {origin} | {len(members):,} | {counts['done']:,} | {counts['remaining']:,} "
                     f"| {counts['retired']:,} |")
    lines += ["", "| Header criterion | Headers failing | Sites remaining |", "| --- | ---: | ---: |"]
    lines.append(f"| `.hpp` extension | {sum(1 for row in active if not row['path'].endswith('.hpp')):,} | |")
    lines.append(f"| `generated` (in `copy_manifest.json`) | "
                 f"{sum(1 for row in active if row['generated'] == 'yes'):,} | |")
    lines.append(f"| `guard` (`#pragma once`) | {sum(1 for row in active if row['guard'] != PRAGMA_ONCE):,} | |")
    for column in [*COUNTS, "c_wrapped", "baseline"]:
        lines.append(f"| `{column}` | {sum(1 for row in active if row[column] != '0'):,} "
                     f"| {sum(int(row[column]) for row in active):,} |")
    lines += ["", "| Source origin | Sources | Done | Remaining | `c_linkage` sites remaining |",
              "| --- | ---: | ---: | ---: | ---: |"]
    for origin in ("generated", "owned", "legacy"):
        members = [row for row in sources if row["origin"] == origin]
        counts = Counter(row["status"] for row in members)
        sites = sum(int(row["c_linkage"]) for row in linked if row["origin"] == origin)
        lines.append(f"| {origin} | {len(members):,} | {counts['done']:,} | {counts['remaining']:,} | {sites:,} |")
    projects: dict[str, Counter[str]] = {}
    for row in rows:
        projects.setdefault(row["path"].split("/")[1], Counter())[f"{row['kind']} {row['status']}"] += 1
    lines += ["", "| Project | Headers done | Headers remaining | Sources done | Sources remaining |",
              "| --- | ---: | ---: | ---: | ---: |"]
    lines += [f"| {name} | {counts['header done']:,} | {counts['header remaining']:,} | {counts['source done']:,} "
              f"| {counts['source remaining']:,} |" for name, counts in sorted(projects.items())]
    return "\n".join(lines)


def write_tracker(workspace: HeaderWorkspace, rows: list[dict[str, str]]) -> None:
    gates.write_tracker_block(workspace.tracker, SUMMARY_BEGIN, SUMMARY_END, summary(rows))


def check(workspace: HeaderWorkspace) -> list[Issue]:
    def issue(rule: str, subject: str, message: str) -> Issue:
        return Issue("headers", rule, subject, message)

    if not workspace.ledger.is_file():
        return [issue("ledger-missing", str(workspace.ledger), "run headers.py --sync")]
    scanner = Scanner(workspace)
    rows = read_csv(workspace.ledger)
    # Once no source keeps C linkage, it is retired everywhere: a header still remaining for other criteria must not
    # regain it, which a stale-ledger finding alone would let a sync record.
    linkage_retired = not any(row["kind"] == "source" and row["status"] == "remaining" for row in rows)
    found = []
    tracked = set()
    for row in rows:
        subject = f"{row['id']} {row['path']}"
        tracked.add(row["path"])
        if row["status"] not in STATUS_VALUES:
            found.append(issue("status-unknown", subject, f"status {row['status']!r} is not one of the states"))
            continue
        if row["status"] == "retired":
            if scanner.exists(row["path"]):
                found.append(issue("retired-present", subject, "a retired file still exists"))
            if not row["notes"].strip():
                found.append(issue("retired-without-reason", subject, "retired needs a note saying why"))
            continue
        if not scanner.exists(row["path"]):
            moved = renamed(row["path"], scanner, set()) if row["kind"] == "header" else row["path"]
            found.append(issue("file-missing", subject, f"renamed to {moved}; run --sync" if moved != row["path"]
                               else "file is gone; mark it retired with a note or update its path"))
            continue
        values = scanner.values(row["path"])
        missed = failures(row["path"], values)
        if row["status"] == "done" and missed:
            found.append(issue(f"{row['kind']}-regressed", subject, f"a done {row['kind']} fails {', '.join(missed)}"))
        else:
            if linkage_retired and values["c_linkage"] != "0":
                found.append(issue("c-linkage-reintroduced", subject, "C linkage is retired in every file; use C++ "
                                   "linkage (Docs/CPP_HEADERS.md)"))
            returned = [column for column in RETIRED_CRITERIA if row["kind"] == "header" and values[column] != "0"]
            if returned:
                forms = "; ".join(f"{column}: {RETIRED_CRITERIA[column]}" for column in returned)
                found.append(issue("criterion-reintroduced", subject, f"{', '.join(returned)} retired in every "
                                   f"header; use the C++ form ({forms})"))
        expected = measured_row(row, scanner)
        if any(row[column] != expected[column] for column in [*MEASURED, "status"]):
            found.append(issue("ledger-stale", subject, "measurements differ from the source; run --sync"))
    for path in [*scanner.headers(), *scanner.sources()]:
        if path in tracked:
            continue
        values = scanner.values(path)
        if c_style(path, values):
            found.append(issue(f"{kind_of(path)}-new", path, f"untracked C-style {kind_of(path)} fails "
                               f"{', '.join(failures(path, values))}; write it as C++ (Docs/CPP_HEADERS.md)"))
    return found + gates.stale_tracker("headers", workspace.tracker, SUMMARY_BEGIN, SUMMARY_END, summary(rows))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sync", action="store_true")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    workspace = HeaderWorkspace()
    if arguments.sync:
        sync(workspace)
    issues = check(workspace)
    for found in issues[:50]:
        print(f"{found.rule}: {found.subject}: {found.message}")
    rows = read_csv(workspace.ledger)
    status = Counter(f"{row['kind']} {row['status']}" for row in rows)
    print(f"{len(rows):,} tracked files: {dict(sorted(status.items()))}; {len(issues)} violations")
    return 1 if issues and arguments.check else 0


if __name__ == "__main__":
    sys.exit(main())
