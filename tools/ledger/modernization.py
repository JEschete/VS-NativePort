"""Track the per-function work between compiling as C++ and being promoted C++ (plan section 8.2).

  python tools\\ledger\\modernization.py --sync                 refresh measured columns and the tracker block
  python tools\\ledger\\modernization.py --sync --coverage T --replay-coverage R
                                                              also replace the regression columns from llvm-cov JSON
  python tools\\ledger\\modernization.py --check                exit 1 on an inconsistent ledger

Docs\\ledgers\\MODERNIZATION_LEDGER.csv has one row per port target. CPP_PROMOTION.csv stays the authority for promotion
steps and FUNCTION_CATALOG.csv for `cpp`: this ledger copies them and never raises them. Only `status` and `notes` are
written by hand. Consumer and blocker columns describe the revision of the last --sync, so ordinary source edits do not
fail --check; a row that moved, appeared or disappeared does.
"""
