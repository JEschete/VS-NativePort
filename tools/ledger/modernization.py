class ModernizationWorkspace(gates.Workspace):
    def __init__(self, root: Path = gates.ROOT) -> None:
        super().__init__(root)
        self.ledger = self.root / "Docs" / "ledgers" / "MODERNIZATION_LEDGER.csv"
        self.tracker = self.root / "Docs" / "MODERNIZATION.md"


def roadmap_for(path: str) -> tuple[str, str]:
    matches = [prefix for prefix in ROADMAP if path.startswith(prefix)]
    return ROADMAP[max(matches, key=len)] if matches else UNASSIGNED


def leaf(symbol: str) -> str:
    return symbol.rsplit("::", 1)[-1]


def coverage_name(name: str) -> str:
    """The plain function name of an llvm-cov record: C, file-prefixed static, or MSVC-mangled C++."""
    if name.startswith("?"):
        return name[1:].split("@", 1)[0]
    return name.rsplit(":", 1)[-1]


def read_coverage(export: dict) -> dict[str, tuple[bool, int]]:
    best: dict[str, tuple[bool, int]] = {}
    for dataset in export["data"]:
        for function in dataset["functions"]:
            regions = [region for region in function["regions"] if region[-1] == 0]
            covered = sum(1 for region in regions if region[4] > 0)
            percent = PERCENT * covered // len(regions) if regions else 0
            found = (function["count"] > 0, percent)
            name = coverage_name(function["name"])
            best[name] = max(best.get(name, found), found)
    return best


def expected_rows(workspace: ModernizationWorkspace) -> tuple[list[dict[str, str]], dict[str, str]]:
    """Every port target in catalog order with the implementation symbol of the owned ones."""
    owned = {row["id"]: row["name"] for row in read_csv(workspace.owned) if row["kind"] == "function"}
    rows = [row for row in read_csv(workspace.catalog)
            if row["copy"] == "yes" and row["copied"] != "retired"]
    return rows, owned


def shim_sites(sources: gates.Sources) -> dict[str, list[str]]:
    """Each transitional SDK shim call that still records itself as unported."""
    found: dict[str, list[str]] = {}
    for path, text in sorted(sources.text.items()):
        if "/Legacy/" in path:
            sites = SHIM_SITE.findall(gates.strip_source(text, keep_strings=True))
            if sites:
                found[path] = sorted(sites)
    return found


class Measure:
    """Native facts about one function, read once per sync from the same parser the gates use."""

    def __init__(self, workspace: ModernizationWorkspace) -> None:
        self.sources = gates.Sources(workspace)
        self.settings = gates.compile_settings(workspace)
        self.generated = {slash(path) for path in json.loads(workspace.manifest.read_text(encoding="utf-8"))}
        self.aliases: dict[str, str] = {}
        self.instances: dict[str, str] = {}
        self.legacy: set[str] = set()
        self.by_file: dict[str, dict[str, gates.Definition]] = {}
        for path, text in self.sources.text.items():
            for name, target in ALIAS.findall(gates.strip_source(text)):
                if TEMPLATE_NAME.match(name):
                    self.instances[target] = name
                else:
                    self.aliases[name] = target
            if "/Legacy/" in path:
                self.legacy |= {leaf(item.qualified) for item in self.sources.definitions(path)}

    def definitions(self, path: str) -> dict[str, gates.Definition]:
        if path not in self.by_file:
            self.by_file[path] = {leaf(item.qualified): item for item in self.sources.definitions(path)}
        return self.by_file[path]

    def find(self, symbol: str, path: str) -> gates.Definition | None:
        name = leaf(symbol)
        for candidate in [path, *sorted(self.sources.tokens.get(name, ()))]:
            found = self.definitions(candidate).get(name)
            if found:
                return found
        return None

    def resolve(self, symbol: str, catalog_name: str, path: str) -> tuple[str, gates.Definition | None]:
        """Where the body lives: here, in the template this row instantiates or is, or behind a macro alias."""
        definition = self.find(symbol, path)
        if definition:
            return "found", definition
        name = leaf(symbol)
        if name in self.instances:
            return f"instance:{self.instances[name]}", self.find(self.instances[name], path)
        if TEMPLATE_NAME.match(catalog_name):
            return f"template:{catalog_name}", self.find(catalog_name, path)
        if name in self.aliases:
            return f"alias:{self.aliases[name]}", self.find(self.aliases[name], path)
        return "missing", None

    def consumers(self, symbol: str, path: str) -> dict[str, str]:
        counts: Counter[str] = Counter()
        for user in self.sources.tokens.get(leaf(symbol), ()):
            if user == path or user.endswith(HEADER_SUFFIXES):
                continue
            if user == MODULE_TABLE:
                counts["module_table"] = 1
            elif user.startswith("Native/Tests/"):
                counts["test_consumers"] += 1
            elif user in self.generated:
                counts["generated_consumers"] += 1
            else:
                counts["hand_consumers"] += 1
        return {
            "generated_consumers": str(counts["generated_consumers"]),
            "hand_consumers": str(counts["hand_consumers"]),
            "test_consumers": str(counts["test_consumers"]),
            "module_table": "x" if counts["module_table"] else "",
        }

    def blockers(self, definition: gates.Definition | None) -> dict[str, str]:
        if not definition:
            return {"legacy_calls": "", "legacy_signature": ""}
        calls = sorted(self.legacy & set(gates.IDENTIFIER.findall(definition.body)))
        return {
            "legacy_calls": ";".join(calls),
            "legacy_signature": "x" if gates.LEGACY_SIGNATURE_TYPES.search(definition.signature) else "",
        }


def regression_state(record: str, tests: str, replays: str) -> str:
    if record:
        return "recorded"
    if "yes" in (tests, replays):
        return "executed"
    return "characterize-first" if "no" in (tests, replays) else "unmeasured"


def merged_coverage(export: dict | None, measure: Measure) -> dict[str, tuple[bool, int]] | None:
    """Coverage per name, with each template credited by whichever of its instances ran."""
    if export is None:
        return None
    coverage = read_coverage(export)
    for instance, template in measure.instances.items():
        if instance in coverage:
            coverage[template] = max(coverage.get(template, coverage[instance]), coverage[instance])
    return coverage


def coverage_columns(
    coverage: dict[str, tuple[bool, int]] | None, name: str, old: str,
) -> tuple[str, int]:
    if coverage is None:
        return old, 0
    hit, region = coverage.get(name, (False, 0))
    return ("yes" if hit else "no"), region


def verify_records(workspace: ModernizationWorkspace) -> dict[str, str]:
    records: dict[str, str] = {}
    for row in read_csv(workspace.verify):
        for identifier in gates.split_list(row["ids"]):
            records.setdefault(identifier, row["record"])
    return records


def build_rows(
    workspace: ModernizationWorkspace, tests: dict | None, replays: dict | None,
) -> list[dict[str, str]]:
    catalog, owned = expected_rows(workspace)
    measure = Measure(workspace)
    promotion = {row["id"]: row for row in read_csv(workspace.promotion)}
    records = verify_records(workspace)
    previous = {row["id"]: row for row in read_csv(workspace.ledger)}
    test_coverage = merged_coverage(tests, measure)
    replay_coverage = merged_coverage(replays, measure)
    rows = []
    for item in catalog:
        identifier = item["id"]
        path = slash(item["final_location"])
        symbol = owned.get(identifier) or gates.c_symbol(item["final_name"])
        body, definition = measure.resolve(symbol, item["name"], path)
        old = previous.get(identifier, {})
        kind, _, target = body.partition(":")
        name = target if kind in {"alias", "template"} else leaf(symbol)
        executed, test_region = coverage_columns(test_coverage, name, old.get("tests_execute", ""))
        replayed, replay_region = coverage_columns(replay_coverage, name, old.get("replay_execute", ""))
        measured = test_coverage is not None or replay_coverage is not None
        percent = str(max(test_region, replay_region)) if measured else old.get("region_pct", "")
        record = records.get(identifier, "")
        issue, step = roadmap_for(item["final_location"])
        steps = promotion.get(identifier, {})
        rows.append({
            "id": identifier, "symbol": symbol, "final_name": item["final_name"], "path": item["final_location"],
            "track": "owned" if identifier in owned else "generated",
            "status": old.get("status") or ("done" if item["cpp"] == "x" else "todo"),
            "issue": issue, "imp_step": step, "lines": item["lines"],
            "compile": measure.settings.get(path, {}).get("compile", "unbuilt"), "body": body,
            "copied": item["copied"],
            **{name: steps.get(name, "") for name in gates.STEPS},
            **measure.consumers(symbol, path), **measure.blockers(definition),
            "source_flags": ";".join(flag for flag in SOURCE_FLAGS if item[flag] not in {"", "0"}),
            "tests_execute": executed, "replay_execute": replayed, "region_pct": percent, "verify_record": record,
            "regression": regression_state(record, executed, replayed), "notes": old.get("notes", ""),
        })
    return rows


def write_ledger(workspace: ModernizationWorkspace, rows: list[dict[str, str]]) -> None:
    gates.write_rows(
        workspace.ledger, [FIELDS, *[[row[name] for name in FIELDS] for row in rows]],
        gates.csv_line_terminator(workspace.catalog),
    )


def step_order(step: str) -> tuple[int, str]:
    """Roadmap order, where 30A follows 30 and a row with no step comes last."""
    digits = step.rstrip("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
    return (int(digits), step) if digits else (UNASSIGNED_ORDER, step)


def table_row(label: str, rows: list[dict[str, str]]) -> str:
    regression = Counter(row["regression"] for row in rows)
    open_rows = [row for row in rows if row["status"] != "done"]
    return (
        f"| {label} | {sum(1 for row in open_rows if row['track'] == 'owned')} "
        f"| {sum(1 for row in open_rows if row['track'] == 'generated')} "
        f"| {sum(int(row['lines'] or 0) for row in open_rows):,} "
        f"| {regression['recorded'] + regression['executed']} | {regression['characterize-first']} "
        f"| {regression['unmeasured']} |"
    )


def summary(rows: list[dict[str, str]], sites: dict[str, list[str]]) -> str:
    groups: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        groups[(row["imp_step"], row["issue"])].append(row)
    lines = [
        "| Roadmap step and issue | Owned left | Generated left | Original lines | Under test | Characterize first "
        "| Unmeasured |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for (step, issue), members in sorted(groups.items(), key=lambda item: step_order(item[0][0])):
        label = (f"{step}: #{issue} {ISSUE_SCOPES.get(issue, '')}".rstrip() if issue != "none"
                 else "**no roadmap issue**")
        lines.append(table_row(label, members))
    lines.append(table_row("**Total**", rows))
    lines += ["", "| Status | Functions |", "| --- | ---: |"]
    for status, count in sorted(Counter(row["status"] for row in rows).items()):
        lines.append(f"| {status} | {count:,} |")
    bodies = Counter(row["body"].split(":", 1)[0] for row in rows)
    open_owned = [row for row in rows if row["track"] == "owned" and row["status"] != "done"]
    blocked = sum(1 for row in open_owned if int(row["generated_consumers"]) > 0)
    lines += [
        "",
        "| Measured blocker, open functions | Owned | Generated |",
        "| --- | ---: | ---: |",
    ]
    open_generated = [row for row in rows if row["track"] == "generated" and row["status"] != "done"]
    for label, test in (
        ("Called from generated code", lambda row: int(row["generated_consumers"]) > 0),
        ("Referenced by the original-address module table", lambda row: row["module_table"] == "x"),
        ("Calls an SDK shim", lambda row: bool(row["legacy_calls"])),
        ("Signature uses SDK integer types or `void*`", lambda row: row["legacy_signature"] == "x"),
        ("Compiled with relaxed settings", lambda row: row["compile"] == "relaxed"),
    ):
        lines.append(f"| {label} | {sum(map(test, open_owned)):,} | {sum(map(test, open_generated)):,} |")
    lines += [
        "",
        f"Function bodies: {bodies['found']:,} found, {bodies['alias']:,} macro aliases, "
        f"{bodies['template']:,} templates with {bodies['instance']:,} instances, {bodies['missing']:,} not located. "
        f"{blocked} of {len(open_owned)} open owned functions have generated callers.",
        "",
        f"SDK shim sites still recording `VS_UNPORTED`: {sum(map(len, sites.values()))}.",
        "",
        "| Shim source | Sites | Calls |",
        "| --- | ---: | --- |",
    ]
    for path, names in sites.items():
        lines.append(f"| `{path}` | {len(names)} | {', '.join(f'`{name}`' for name in names)} |")
    return "\n".join(lines)


def tracker_text(current: str, block: str) -> str:
    start = current.find(SUMMARY_BEGIN)
    end = current.find(SUMMARY_END)
    if start < 0 or end < 0:
        raise SystemExit(f"tracker has no {SUMMARY_BEGIN!r} block")
    return f"{current[:start]}{SUMMARY_BEGIN}\n\n{block}\n\n{current[end:]}"


def write_tracker(workspace: ModernizationWorkspace, rows: list[dict[str, str]]) -> None:
    current = workspace.tracker.read_bytes().decode("utf-8").replace("\r\n", "\n")
    text = tracker_text(current, summary(rows, shim_sites(gates.Sources(workspace))))
    workspace.tracker.write_bytes(text.encode("utf-8"))


def sync(workspace: ModernizationWorkspace, tests: dict | None = None, replays: dict | None = None) -> None:
    rows = build_rows(workspace, tests, replays)
    write_ledger(workspace, rows)
    write_tracker(workspace, rows)


def check(workspace: ModernizationWorkspace) -> list[Issue]:
    def issue(rule: str, subject: str, message: str) -> Issue:
        return Issue("modernization", rule, subject, message)

    if not workspace.ledger.is_file():
        return [issue("ledger-missing", str(workspace.ledger), "run modernization.py --sync")]
    found: list[Issue] = []
    rows = read_csv(workspace.ledger)
    by_id = {row["id"]: row for row in rows}
    catalog, owned = expected_rows(workspace)
    wanted = {row["id"]: row for row in catalog}
    for identifier in sorted(wanted.keys() ^ by_id.keys()):
        found.append(issue("ledger-stale", identifier, "catalog and ledger disagree on this row; run --sync"))
    for identifier, row in by_id.items():
        target = wanted.get(identifier)
        if target and (row["path"] != target["final_location"]
                       or row["track"] != ("owned" if identifier in owned else "generated")):
            found.append(issue("ledger-stale", identifier, "function moved or changed ownership; run --sync"))
        if row["status"] not in STATUS_VALUES:
            found.append(issue("status-unknown", identifier, f"status {row['status']!r} is not one of the states"))
        if row["status"] in {"in-progress", "done"} and row["regression"] not in COVERED:
            found.append(issue("work-without-regression", identifier,
                               f"regression is {row['regression']!r}: characterize the behavior before changing it"))
        promoted = bool(target) and target["cpp"] == "x"
        if row["status"] == "done" and not promoted:
            found.append(issue("done-not-promoted", identifier, "done needs catalog cpp=x"))
        if promoted and row["status"] != "done":
            found.append(issue("promoted-not-done", identifier, "catalog cpp=x needs status done"))
    current = workspace.tracker.read_bytes().decode("utf-8").replace("\r\n", "\n")
    if tracker_text(current, summary(rows, shim_sites(gates.Sources(workspace)))) != current:
        found.append(issue("tracker-stale", str(workspace.tracker), "tracker block differs from the ledger; run --sync"))
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sync", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--coverage", type=Path, help="llvm-cov export JSON of the unit tests")
    parser.add_argument("--replay-coverage", type=Path, help="llvm-cov export JSON of the scenario replays")
    arguments = parser.parse_args()
    workspace = ModernizationWorkspace()
    if arguments.sync:
        exports = [json.loads(path.read_text(encoding="utf-8")) if path else None
                   for path in (arguments.coverage, arguments.replay_coverage)]
        sync(workspace, *exports)
    issues = check(workspace)
    for found in issues:
        print(f"{found.rule}: {found.subject}: {found.message}")
    rows = read_csv(workspace.ledger)
    print(f"{len(rows)} functions: {dict(sorted(Counter(row['status'] for row in rows).items()))}; "
          f"{len(issues)} violations")
    return 1 if issues and arguments.check else 0


