"""Enforce the dependency matrix between VS.Engine, VS.Content and VS.Game, and track the includes still crossing it.

  python tools\\ledger\\boundaries.py --sync    mark crossings that are gone resolved, refresh the tracker
  python tools\\ledger\\boundaries.py --check   exit 1 on a new or returned crossing, a stale ledger or a stale project

Docs\\plan\\LAYOUT.md (plan section 3) defines the matrix: Game owns domain state, decisions and snapshots; Engine
owns generic mechanisms; Content returns decoded values or handles. Each Engine system, Content and Game is a layer,
and ALLOWED lists the layers a layer may include. Docs\\ledgers\\BOUNDARY_LEDGER.csv has a row for every quoted include
in Native\\Engine or Native\\Content that crosses the matrix: `remaining` while the include is there and `resolved` once
it is gone. `resolved` is sticky: the include returning fails --check. Rows are only created when the ledger is first
written, so a new crossing fails --check rather than joining the ledger. tools\\scaffold\\gen_solution.py gives the
Game include directories only to the Engine and Content sources with a remaining crossing into Game, so the compiler
rejects any other include of a Game header there as well.
Tracked in issue #43.
"""
from __future__ import annotations

import posixpath
import re
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gates  # noqa: E402
from gates import Issue, read_csv, slash  # noqa: E402

SUMMARY_BEGIN = "<!-- boundaries:begin (generated by tools/ledger/boundaries.py --sync) -->"
SUMMARY_END = "<!-- boundaries:end -->"
FIELDS = ["id", "file", "from_layer", "header", "to_layer", "status", "notes"]
STATUS_VALUES = {"remaining", "resolved"}
SUFFIXES = (".cpp", ".hpp", ".h", ".inl")
# The libraries whose includes the matrix limits. Game, the executables and the tests may include any library.
BOUNDED = ("Native/Engine", "Native/Content")
# Include roots besides each project's include\ and src\: the Legacy shims (Directory.Build.props VSLegacyIncludes).
LEGACY_ROOTS = {"Native/Engine", "Native/Content"}
QUOTED_INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]*"(?P<name>[^"]+)"', re.M)
COPIED_INCLUDE = re.compile(r'<ClCompile Include="(?P<path>[^"]+)">\s*<AdditionalIncludeDirectories>\$\(VSCopiedCIncludes\)')

FOUNDATION = ("Engine.Core", "Engine.Platform")
# Engine.Legacy is the PS1 SDK aggregate (Engine\Legacy\Psx.hpp); Engine\Legacy\<System>\ belongs to its system.
MECHANISMS = ("Engine.Render", "Engine.Audio", "Engine.Input", "Engine.Movie", "Engine.Save", "Engine.Legacy")
ALLOWED: dict[str, frozenset[str]] = {
    "Engine.Core": frozenset({"Engine.Core"}),
    "Engine.Platform": frozenset(FOUNDATION),
    **{layer: frozenset({*FOUNDATION, *MECHANISMS, "Content"}) for layer in MECHANISMS},
    "Content": frozenset({*FOUNDATION, "Content"}),
}


@dataclass(frozen=True, order=True)
class Crossing:
    file: str
    header: str
    from_layer: str
    to_layer: str


def layer_of(path: str) -> str:
    """The layer a Native path belongs to: `Engine.<System>`, `Content`, `Game` or another project's name."""
    parts = path.split("/")
    if parts[1] != "Engine":
        return parts[1]
    if parts[2] == "Legacy" and len(parts) == 4:
        return "Engine.Legacy"
    return f"Engine.{parts[3]}" if len(parts) > 4 else "Engine"


class Scanner:
    def __init__(self, root: Path) -> None:
        self.root = root
        native = root / "Native"
        self.files = sorted(slash(str(path.relative_to(root))) for path in native.rglob("*")
                            if path.suffix in SUFFIXES and path.is_file())
        self.headers = {path for path in self.files if not path.endswith(".cpp")}

    def text(self, path: str) -> str:
        return (self.root / path).read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n")

    def resolve(self, includer: str, name: str) -> str | None:
        """The header a quoted include names: the includer's directory first, then the include roots, preferring the
        includer's own project. None for a header outside Native (a library) or an ambiguous name."""
        local = posixpath.normpath(posixpath.join(posixpath.dirname(includer), name))
        if local in self.headers:
            return local
        roots = [path for path in self.headers if path.endswith(f"/{name}")
                 and (posixpath.basename(path[:-len(name) - 1]) in {"include", "src"}
                      or path[:-len(name) - 1] in LEGACY_ROOTS)]
        project = [path for path in roots if path.split("/")[1] == includer.split("/")[1]]
        found = project or roots
        return found[0] if len(found) == 1 else None

    def unknown_layers(self) -> list[str]:
        return [path for path in self.files if path.startswith(BOUNDED) and layer_of(path) not in ALLOWED]

    def crossings(self) -> list[Crossing]:
        found = set()
        for path in self.files:
            source = layer_of(path)
            if not path.startswith(BOUNDED) or source not in ALLOWED:
                continue
            for match in QUOTED_INCLUDE.finditer(self.text(path)):
                target = self.resolve(path, match.group("name"))
                if target is None:
                    continue
                destination = layer_of(target)
                if destination != source and destination not in ALLOWED[source]:
                    found.add(Crossing(path, target, source, destination))
        return sorted(found)


def key(row: dict[str, str]) -> tuple[str, str]:
    return row["file"], row["header"]


def initial_rows(crossings: list[Crossing]) -> list[dict[str, str]]:
    return [{"id": f"B{index:04d}", "file": item.file, "from_layer": item.from_layer, "header": item.header,
             "to_layer": item.to_layer, "status": "remaining", "notes": ""}
            for index, item in enumerate(crossings, 1)]


def sync(root: Path) -> None:
    ledger = ledger_path(root)
    scanner = Scanner(root)
    crossings = scanner.crossings()
    previous = read_csv(ledger)
    if not previous:
        rows = initial_rows(crossings)
    else:
        present = {(item.file, item.header) for item in crossings}
        rows = [{**row, "status": "resolved"} if row["status"] == "remaining" and key(row) not in present else row
                for row in previous]
    terminator = gates.csv_line_terminator(ledger) if ledger.is_file() else "\n"
    gates.write_rows(ledger, [FIELDS, *[[row[name] for name in FIELDS] for row in rows]], terminator)
    gates.write_tracker_block(tracker_path(root), SUMMARY_BEGIN, SUMMARY_END, summary(rows))


def ledger_path(root: Path) -> Path:
    return root / "Docs" / "ledgers" / "BOUNDARY_LEDGER.csv"


def tracker_path(root: Path) -> Path:
    return root / "Docs" / "plan" / "LAYOUT.md"


def summary(rows: list[dict[str, str]]) -> str:
    remaining = [row for row in rows if row["status"] == "remaining"]
    resolved = [row for row in rows if row["status"] == "resolved"]
    files = {row["file"] for row in remaining}
    lines = [
        f"**{len(resolved):,} of {len(rows):,} crossing includes resolved**, {len(remaining):,} remaining in "
        f"{len(files):,} files.",
        "",
        "| From | To | Remaining includes | Remaining files | Resolved includes |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    rules = sorted({(row["from_layer"], row["to_layer"]) for row in rows})
    for source, destination in rules:
        members = [row for row in rows if (row["from_layer"], row["to_layer"]) == (source, destination)]
        open_rows = [row for row in members if row["status"] == "remaining"]
        lines.append(f"| {source} | {destination} | {len(open_rows):,} | {len({row['file'] for row in open_rows}):,} "
                     f"| {len(members) - len(open_rows):,} |")
    lines += ["", "| Remaining file | Crosses into | Includes |", "| --- | --- | ---: |"]
    for path in sorted(files):
        members = [row for row in remaining if row["file"] == path]
        targets = ", ".join(sorted({row["to_layer"] for row in members}))
        lines.append(f"| `{path}` | {targets} | {len(members):,} |")
    return "\n".join(lines)


def project_game_sources(root: Path) -> set[str]:
    """The Engine and Content sources the generated projects compile with the Game include directories."""
    found = set()
    for project in ("Engine/VS.Engine.vcxproj", "Content/VS.Content.vcxproj"):
        path = root / "Native" / project
        if not path.is_file():
            continue
        base = posixpath.dirname(f"Native/{project}")
        text = path.read_text(encoding="utf-8-sig")
        found |= {posixpath.normpath(posixpath.join(base, slash(match.group("path"))))
                  for match in COPIED_INCLUDE.finditer(text)}
    return found


def check(root: Path) -> list[Issue]:
    def issue(rule: str, subject: str, message: str) -> Issue:
        return Issue("boundaries", rule, subject, message)

    ledger = ledger_path(root)
    if not ledger.is_file():
        return [issue("ledger-missing", str(ledger), "run boundaries.py --sync")]
    scanner = Scanner(root)
    found = [issue("layer-unknown", path, f"{layer_of(path)} is not a layer of the dependency matrix; add it to "
                   "ALLOWED and to the plan's section 3") for path in scanner.unknown_layers()]
    crossings = {(item.file, item.header): item for item in scanner.crossings()}
    rows = read_csv(ledger)
    tracked = {}
    for row in rows:
        subject = f"{row['id']} {row['file']} -> {row['header']}"
        tracked[key(row)] = row
        if row["status"] not in STATUS_VALUES:
            found.append(issue("status-unknown", subject, f"status {row['status']!r} is not one of the states"))
            continue
        present = crossings.get(key(row))
        if row["status"] == "resolved":
            if present:
                found.append(issue("crossing-returned", subject, f"a resolved include of {row['to_layer']} is back; "
                                   "use the narrow contract that replaced it"))
        elif not present:
            found.append(issue("ledger-stale", subject, "the include is gone; run --sync to mark it resolved"))
        elif (present.from_layer, present.to_layer) != (row["from_layer"], row["to_layer"]):
            found.append(issue("ledger-stale", subject, f"now {present.from_layer} -> {present.to_layer}; correct "
                               "the row"))
    for crossing_key, item in sorted(crossings.items()):
        if crossing_key not in tracked:
            found.append(issue("crossing-new", f"{item.file} -> {item.header}", f"{item.from_layer} may not include "
                               f"{item.to_layer} (plan section 3); give the owner a narrow contract instead"))
    expected = {row["file"] for row in rows if row["status"] == "remaining" and row["to_layer"] == "Game"
                and row["file"].endswith(".cpp")}
    actual = project_game_sources(root)
    for path in sorted(expected ^ actual):
        state = "lacks" if path in expected else "still has"
        found.append(issue("project-stale", path, f"the generated project {state} the Game include directories; "
                           "run tools\\scaffold\\gen_solution.py"))
    return found + gates.stale_tracker("boundaries", tracker_path(root), SUMMARY_BEGIN, SUMMARY_END, summary(rows))


def report(root: Path, issues: list[Issue]) -> str:
    status = Counter(row["status"] for row in read_csv(ledger_path(root)))
    return f"{sum(status.values()):,} crossing includes: {dict(sorted(status.items()))}; {len(issues)} violations"


if __name__ == "__main__":
    sys.exit(gates.ledger_tool_main(__doc__, sync, check, report))
