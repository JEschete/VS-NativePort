def function_ids(workspace: gates.Workspace) -> dict[str, str]:
    names: dict[str, str] = {}
    for row in read_csv(workspace.catalog):
        if row["copy"] == "yes":
            names.setdefault(leaf(gates.c_symbol(row["final_name"])), row["id"])
            names.setdefault(row["name"], row["id"])
    for row in read_csv(workspace.owned):
        if row["kind"] == "function":
            names[leaf(row["name"])] = row["id"]
    return names


def guarded_before(body: str, name: str, position: int) -> bool:
    """Whether `name`, an escaped expression, is tested anywhere before this position in the function."""
    guard = re.compile(
        rf"!\s*{name}{NOT_A_MEMBER}|(?<![\w\]>.]){name}\s*(?:[!=]=|&&|\|\||\?)|\b(?:if|while)\s*\(\s*{name}\s*\)"
        rf"|;\s*{name}\s*;"
        rf"|(?:&&|\|\|)\s*{name}\s*[)&|]"
    )
    return any(match.start() < position for match in guard.finditer(body))


def guarded_after(body: str, name: str, position: int) -> bool:
    guard = re.compile(
        rf"!\s*{name}{NOT_A_MEMBER}|(?<![\w\]>.]){name}\s*[!=]=\s*(?:NULL|nullptr|0)\b|\bif\s*\(\s*{name}\s*\)")
    reassigned = re.compile(rf"(?<![\w>.]){name}\s*=[^=]")
    for match in guard.finditer(body):
        if match.start() > position:
            return not reassigned.search(body, position, match.start())
    return False


class FunctionScan:
    """Every pattern class applied to one function body."""

    def __init__(self, tables: dict[str, str]) -> None:
        self.tables = tables

    def null_tables(self, body: str) -> list[tuple[str, str, str, str]]:
        found = []
        for table in self.tables:
            if table not in body:
                continue
            for match in re.finditer(rf"\b{table}\[(?P<index>[^\]]*)\]\s*\)*\s*->", body):
                index = match["index"].strip()
                entry = rf"{table}\[{re.escape(index)}\]"
                if guarded_before(body, entry, match.start()):
                    continue
                confidence = "low" if index.isdigit() else "medium"
                found.append(("NULL-TABLE", f"{table}[{index}]", confidence, match.group(0)))
            alias = rf"(?P<alias>[A-Za-z_]\w*)\s*=\s*{CAST}{table}\[(?P<index>[^\]]*)\]\s*;"
            for match in re.finditer(alias, body):
                found += self.alias_reads(body, match, "NULL-TABLE", f"{table}[{match['index'].strip()}]")
        return found

    @staticmethod
    def alias_reads(body: str, match: re.Match[str], hazard_class: str, source: str) -> list[tuple[str, str, str, str]]:
        name = re.escape(match["alias"])
        read = re.compile(rf"(?<![\w>.]){name}\s*->").search(body, match.end())
        if not read or guarded_before(body, name, read.start()):
            return []
        confidence = "low" if source.endswith("[0]") else "medium"
        return [(hazard_class, f"{match['alias']} = {source}", confidence, match.group(0))]

    def null_returns(self, body: str) -> list[tuple[str, str, str, str]]:
        found = [("NULL-RETURN", match["call"], "medium", match.group(0))
                 for match in re.finditer(rf"(?P<call>\b{LOOKUP}){ARGUMENTS}\s*\)*\s*->", body)]
        for match in re.finditer(rf"(?P<alias>[A-Za-z_]\w*)\s*=\s*{CAST}(?P<call>\b{LOOKUP}){ARGUMENTS}\s*;", body):
            found += self.alias_reads(body, match, "NULL-RETURN", match["call"])
        return found

    @staticmethod
    def guards_after_reads(body: str) -> list[tuple[str, str, str, str]]:
        found = []
        seen: set[str] = set()
        for match in re.finditer(r"(?<![\w>.\]])(?<!sizeof )(?P<name>[A-Za-z_]\w*)\s*->", body):
            name = match["name"]
            if name in seen:
                continue
            seen.add(name)
            escaped = re.escape(name)
            if not guarded_before(body, escaped, match.start()) and guarded_after(body, escaped, match.start()):
                found.append(("GUARD-AFTER-READ", name, "medium", match.group(0)))
        return found

    @staticmethod
    def divisions(signature: str, body: str) -> list[tuple[str, str, str, str]]:
        if NOT_A_DIVISION.search(signature) or NOT_A_DIVISION.search(body):
            return []
        found = []
        for match in DIVISION.finditer(body):
            divisor = match["divisor"].strip()
            if LITERAL_DIVISOR.match(divisor):
                continue
            if divisor.startswith("("):
                if not re.search(r"[A-Za-z_]", divisor):
                    continue
                found.append(("DIV-ZERO", divisor, "low", match.group(0)))
            elif not guarded_before(body, re.escape(divisor), match.start()):
                found.append(("DIV-ZERO", divisor, "medium", match.group(0)))
        return found

    @staticmethod
    def layout(body: str) -> list[tuple[str, str, str, str]]:
        found = [("LITERAL-SIZE", match["size"], "medium", match.group(0)) for match in LITERAL_SIZE.finditer(body)]
        found += [("BYTE-OFFSET", " ".join(match.group(0).split()), "medium", match.group(0))
                  for match in BYTE_OFFSET.finditer(body)]
        found += [("PS1-ADDRESS", match.group(0), "low", match.group(0)) for match in PS1_ADDRESS.finditer(body)]
        return found

    @staticmethod
    def capacity_literals(signature: str, body: str) -> list[tuple[str, str, str, str]]:
        if not INVENTORY_MARK.search(signature) and not INVENTORY_MARK.search(body):
            return []
        return [("CAPACITY-LITERAL", f"loop bound {match['size']}", "medium", match.group(0))
                for match in CAPACITY_LOOP.finditer(body) if match["size"] in INVENTORY_CAPACITIES]

    def run(self, definition: gates.Definition) -> list[tuple[str, str, str, str]]:
        body = definition.body
        return [
            *self.null_tables(body), *self.null_returns(body), *self.guards_after_reads(body),
            *self.divisions(definition.signature, body), *self.layout(body),
            *self.capacity_literals(definition.signature, body),
        ]


def in_scope(path: str) -> bool:
    return path.startswith(SCOPES) and path != MODULE_TABLE


def line_of(text: str, snippet: str, start: int = 0) -> int:
    position = text.find(snippet, start)
    if position < 0:
        position = start
    return text.count("\n", 0, position) + 1


def definition_start(text: str, name: str) -> int:
    """Offset of a function's definition: the occurrence whose parameter list is followed by a body."""
    for match in re.finditer(rf"\b{re.escape(name)}\s*\(", text):
        depth = 0
        for position in range(match.end() - 1, len(text)):
            if text[position] == "(":
                depth += 1
            elif text[position] == ")":
                depth -= 1
                if depth == 0:
                    following = text[position + 1:].lstrip()
                    if following.startswith("{"):
                        return match.start()
                    break
    return 0


def declared_tables(sources: gates.Sources) -> dict[str, str]:
    tables: dict[str, str] = {}
    for path, code in sources.code.items():
        if in_scope(path) and path.endswith(HEADER_SUFFIXES):
            for match in TABLE.finditer(code):
                if not SCALAR_ELEMENTS.search(match["type"]):
                    tables[match["name"]] = match["size"]
    return tables


def capacity_rows(sources: gates.Sources, tables: dict[str, str]) -> list[Hazard]:
    rows = []
    for path, code in sorted(sources.code.items()):
        if not in_scope(path) or not path.endswith(HEADER_SUFFIXES):
            continue
        text = sources.text[path]
        for match in TABLE.finditer(code):
            if match["name"] in tables:
                rows.append(Hazard("CAPACITY", path, line_of(text, f"{match['name']}["), match["name"], "",
                                   f"{match['name']}[{match['size']}]", "pattern", "medium"))
        for struct in STRUCT.finditer(code):
            if CAPACITY_STRUCT.match(struct["name"]):
                rows += struct_rows(path, text, struct)
    return rows


def struct_rows(path: str, text: str, struct: re.Match[str]) -> list[Hazard]:
    rows = []
    for field in FIELD.finditer(struct["body"]):
        name = field["name"]
        kind = " ".join(field["type"].split())
        if TEXT_FIELD.match(name):
            continue
        qualified = f"{struct['name']}.{name}"
        definition = re.search(rf"typedef\s+struct\s+{struct['name']}\s*\{{", text)
        line = line_of(text, name, definition.start() if definition else 0)
        if field["size"] and kind not in {"char", "signed char"}:
            rows.append(Hazard("CAPACITY", path, line, struct["name"], "", f"{qualified}[{field['size']}]",
                               "pattern", "medium"))
        if kind in NARROW_TYPES and NARROW_NAME.match(name):
            rows.append(Hazard("NARROW-ID", path, line, struct["name"], "", qualified, "pattern", "medium"))
    return rows


def scan(workspace: gates.Workspace) -> list[Hazard]:
    sources = gates.Sources(workspace)
    ids = function_ids(workspace)
    tables = declared_tables(sources)
    scanner = FunctionScan(tables)
    rows = capacity_rows(sources, tables)
    for path in sorted(sources.text):
        if not in_scope(path):
            continue
        text = sources.text[path]
        code = sources.code[path]
        rows += [Hazard("UNPROTOTYPED-CALL", path, line_of(text, match.group(0)), match["name"], "", match["name"],
                        "pattern", "medium") for match in UNPROTOTYPED.finditer(code)]
        if not path.endswith(SOURCE_SUFFIXES):
            continue
        rows += [Hazard("UNSIZED-ARRAY", path, line_of(text, f"{match['name']}["), match["name"],
                        ids.get(match["name"], ""), match["name"], "pattern", "medium")
                 for match in UNSIZED.finditer(code)]
        for definition in sources.definitions(path):
            name = leaf(definition.qualified)
            start = definition_start(text, name)
            rows += [
                Hazard(hazard_class, path, line_of(text, snippet, start), name, ids.get(name, ""), detail, "pattern",
                       confidence)
                for hazard_class, detail, confidence, snippet in scanner.run(definition)
            ]
    return rows


def parse_compiler_log(log: str, root: str) -> list[Hazard]:
    prefix = slash(str(root)).rstrip("/").lower() + "/"
    seen: set[tuple[str, int, str]] = set()
    rows = []
    for line in log.splitlines():
        match = COMPILER_LINE.match(line)
        if not match or match["flag"] not in COMPILER_CLASSES:
            continue
        path = slash(match["path"].strip())
        if not re.match(r"^[A-Za-z]:/", path) and match["project"]:
            path = slash(os.path.normpath(os.path.join(os.path.dirname(match["project"]), path)))
        if not path.lower().startswith(prefix):
            continue
        relative = path[len(prefix):]
        identity = (relative, int(match["line"]), match["flag"])
        if identity in seen or not relative.startswith(SCOPES):
            continue
        seen.add(identity)
        rows.append(Hazard(COMPILER_CLASSES[match["flag"]], relative, int(match["line"]), "", "",
                           f"-W{match['flag']}: {match['message'][:120]}", "compiler", "high"))
    return rows


def attributed(rows: list[Hazard], workspace: gates.Workspace) -> list[Hazard]:
    """Name the function around each compiler row: the last definition starting at or before its line."""
    sources = gates.Sources(workspace)
    ids = function_ids(workspace)
    starts: dict[str, list[tuple[int, str]]] = {}
    result = []
    for row in rows:
        if row.path not in starts:
            text = sources.text.get(row.path, "")
            names = {leaf(item.qualified) for item in sources.definitions(row.path)}
            starts[row.path] = sorted(
                (line_of(text, "", definition_start(text, name)), name) for name in names
            )
        before = [name for line, name in starts[row.path] if line <= row.line]
        name = before[-1] if before else ""
        result.append(replace(row, symbol=name, function=ids.get(name, "")))
    return result


def keyed(rows: list[Hazard]) -> list[dict[str, str]]:
    """Stable identity across line moves: class, file, function and text, numbered when they repeat."""
    counts: Counter[tuple[str, str, str, str]] = Counter()
    result = []
    for row in sorted(rows, key=lambda item: (item.hazard_class, item.path, item.line, item.detail)):
        identity = (row.hazard_class, row.path, row.symbol, row.detail)
        ordinal = counts[identity]
        counts[identity] += 1
        digest = hashlib.sha256("|".join([*identity, str(ordinal)]).encode()).hexdigest()[:HASH_CHARACTERS]
        issue, step = roadmap_for(row.path.replace("/", "\\"))
        result.append({
            "key": digest, "class": row.hazard_class, "confidence": row.confidence, "evidence": row.evidence,
            "function": row.function, "symbol": row.symbol, "path": row.path, "line": str(row.line),
            "detail": row.detail, "issue": issue, "imp_step": step, "status": "open", "notes": "",
        })
    return result


def write_ledger(workspace: HazardWorkspace, rows: list[dict[str, str]]) -> None:
    gates.write_rows(
        workspace.ledger, [FIELDS, *[[row[name] for name in FIELDS] for row in rows]],
        gates.csv_line_terminator(workspace.catalog),
    )


def summary(rows: list[dict[str, str]]) -> str:
    by_class: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        by_class[row["class"]].append(row)
    lines = [
        "| Class | What it is | Sites | Compiler | High | Medium | Low | Open |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, entry in CLASSES.items():
        members = by_class.get(name, [])
        confidence = Counter(row["confidence"] for row in members)
        lines.append(
            f"| `{name}` | {entry.title} | {len(members):,} "
            f"| {sum(1 for row in members if row['evidence'] == 'compiler'):,} "
            f"| {confidence['high']:,} | {confidence['medium']:,} | {confidence['low']:,} "
            f"| {sum(1 for row in members if row['status'] == 'open'):,} |")
    lines.append(f"| **Total** | | {len(rows):,} | {sum(1 for row in rows if row['evidence'] == 'compiler'):,} "
                 f"| {sum(1 for row in rows if row['confidence'] == 'high'):,} "
                 f"| {sum(1 for row in rows if row['confidence'] == 'medium'):,} "
                 f"| {sum(1 for row in rows if row['confidence'] == 'low'):,} "
                 f"| {sum(1 for row in rows if row['status'] == 'open'):,} |")
    lines += ["", "| Class | On PS1 | Here | Modern C++ replacement |", "| --- | --- | --- | --- |"]
    lines += [f"| `{name}` | {entry.ps1} | {entry.native} | {entry.modern} |" for name, entry in CLASSES.items()]
    groups: Counter[str] = Counter()
    for row in rows:
        groups[f"#{row['issue']}" if row["issue"] != "none" else "no roadmap issue"] += 1
    lines += ["", "| Roadmap issue | Sites |", "| --- | ---: |"]
    lines += [f"| {name} | {count:,} |" for name, count in groups.most_common()]
    return "\n".join(lines)


def tracker_text(current: str, block: str) -> str:
    start = current.find(SUMMARY_BEGIN)
    end = current.find(SUMMARY_END)
    if start < 0 or end < 0:
        raise SystemExit(f"tracker has no {SUMMARY_BEGIN!r} block")
    return f"{current[:start]}{SUMMARY_BEGIN}\n\n{block}\n\n{current[end:]}"


def write_tracker(workspace: HazardWorkspace, rows: list[dict[str, str]]) -> None:
    current = workspace.tracker.read_bytes().decode("utf-8").replace("\r\n", "\n")
    workspace.tracker.write_bytes(tracker_text(current, summary(rows)).encode("utf-8"))


def sync(workspace: HazardWorkspace, compiler_log: str | None = None) -> None:
    previous = {row["key"]: row for row in read_csv(workspace.ledger)}
    rows = keyed(scan(workspace))
    if compiler_log is not None:
        rows += keyed(attributed(parse_compiler_log(compiler_log, str(workspace.root)), workspace))
    else:
        rows += [row for row in previous.values() if row["evidence"] == "compiler"]
    merged = {}
    for row in rows:
        old = previous.get(row["key"])
        merged[row["key"]] = {**row, "status": old["status"], "notes": old["notes"]} if old else row
    ordered = sorted(merged.values(), key=lambda row: (row["class"], row["path"], int(row["line"]), row["key"]))
    write_ledger(workspace, ordered)
    write_tracker(workspace, ordered)


def check(workspace: HazardWorkspace) -> list[Issue]:
    def issue(rule: str, subject: str, message: str) -> Issue:
        return Issue("hazards", rule, subject, message)

    if not workspace.ledger.is_file():
        return [issue("ledger-missing", str(workspace.ledger), "run hazards.py --sync")]
    rows = read_csv(workspace.ledger)
    found = []
    for row in rows:
        if row["status"] not in STATUS_VALUES:
            found.append(issue("status-unknown", row["key"], f"status {row['status']!r} is not one of the states"))
        elif row["status"] != "open" and not row["notes"].strip():
            found.append(issue("triage-without-reason", row["key"], f"{row['status']} needs a note saying why"))
    recorded = {row["key"]: row for row in rows if row["evidence"] == "pattern"}
    current = {row["key"]: row for row in keyed(scan(workspace))}
    for key in sorted(current.keys() - recorded.keys()):
        row = current[key]
        found.append(issue("hazard-new", key, f"{row['class']} {row['path']}:{row['line']} {row['detail']}; "
                                              "fix it, or acknowledge it with --sync"))
    for key in sorted(recorded.keys() - current.keys()):
        row = recorded[key]
        found.append(issue("hazard-gone", key, f"{row['class']} {row['path']} {row['detail']} is gone; run --sync"))
    text = workspace.tracker.read_bytes().decode("utf-8").replace("\r\n", "\n")
    if tracker_text(text, summary(rows)) != text:
        found.append(issue("tracker-stale", str(workspace.tracker), "tracker block differs from the ledger; run --sync"))
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sync", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--compiler-log", type=Path, help="build output whose warnings replace the compiler rows")
    arguments = parser.parse_args()
    workspace = HazardWorkspace()
    if arguments.sync:
        log = None
        if arguments.compiler_log:
            log = arguments.compiler_log.read_bytes().decode("utf-8", errors="replace").replace("\x00", "")
        sync(workspace, log)
    issues = check(workspace)
    for found in issues[:50]:
        print(f"{found.rule}: {found.subject}: {found.message}")
    rows = read_csv(workspace.ledger)
    print(f"{len(rows):,} hazard sites: {dict(Counter(row['class'] for row in rows).most_common())}; "
          f"{len(issues)} violations")
    return 1 if issues and arguments.check else 0


if __name__ == "__main__":
    sys.exit(main())
