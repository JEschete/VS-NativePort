def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        return []
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def slash(path: str) -> str:
    return path.replace("\\", "/")


def split_list(value: str) -> list[str]:
    return [item.strip() for item in value.split(";") if item.strip()]


def c_symbol(final_name: str) -> str:
    return final_name.replace("::", "_")


def strip_source(text: str, *, keep_strings: bool = False) -> str:
    """Remove comments (and optionally string/character contents) so braces and identifiers can be trusted."""
    def replace(match: re.Match[str]) -> str:
        token = match.group(0)
        if token.startswith(("//", "/*")):
            return " "
        if keep_strings:
            return token
        return '""' if not token.startswith("'") else "' '"
    return SOURCE_TOKEN.sub(replace, text)


def find_definitions(text: str) -> list[Definition]:
    """Function definitions at namespace scope with their complete enclosing scope and linkage."""
    source = PREPROCESSOR_LINE.sub("", strip_source(text))
    definitions: list[Definition] = []
    scopes: list[tuple[list[str], bool]] = []
    buffer_start = 0
    index = 0

    def matching_brace(opening: int) -> int:
        depth = 0
        for position in range(opening, len(source)):
            if source[position] == "{":
                depth += 1
            elif source[position] == "}":
                depth -= 1
                if depth == 0:
                    return position
        return len(source) - 1

    while index < len(source):
        character = source[index]
        if character == ";":
            buffer_start = index + 1
        elif character == "}":
            if scopes:
                scopes.pop()
            buffer_start = index + 1
        elif character == "{":
            head = source[buffer_start:index].strip()
            namespace = re.fullmatch(r"(?:inline\s+)?namespace\s*([\w:]*)", head)
            if namespace:
                scopes.append((namespace.group(1).split("::") if namespace.group(1) else ["(anonymous)"], False))
                buffer_start = index + 1
            elif re.fullmatch(r'extern\s*""', head):
                scopes.append(([], True))
                buffer_start = index + 1
            else:
                end = matching_brace(index)
                definition = parse_definition(head, source[index + 1:end], scopes)
                if definition:
                    definitions.append(definition)
                index = end
                buffer_start = end + 1
        index += 1
    return definitions


def parse_definition(head: str, body: str, scopes: list[tuple[list[str], bool]]) -> Definition | None:
    cleaned = re.sub(r"__attribute__\s*\(\(.*?\)\)|__declspec\s*\(.*?\)|\[\[.*?\]\]", " ", head, flags=re.S)
    opening = cleaned.find("(")
    if opening < 0 or "=" in cleaned[:opening]:
        return None
    if re.match(r"\s*(?:template\s*<[^()]*>\s*)?(?:struct|class|union|enum)\b[^()]*$", cleaned[:opening]):
        return None
    name = QUALIFIED_NAME.search(cleaned[:opening])
    if not name or name.group(1) in {"if", "for", "while", "switch", "return"}:
        return None
    parts = [part for names, _ in scopes for part in names]
    qualified = "::".join([*parts, name.group(1).removeprefix("::")])
    return Definition(qualified, cleaned, body, any(linkage for _, linkage in scopes) or 'extern ""' in cleaned)


def is_forwarding_wrapper(definition: Definition, siblings: list[Definition]) -> bool:
    """One statement that only calls something defined elsewhere: a new name, not moved behavior."""
    match = FORWARD_CALL.match(definition.body)
    if not match or definition.body.count(";") != 1:
        return False
    callee = match.group(1).rsplit("::", 1)[-1]
    return not any(
        other is not definition and other.qualified.rsplit("::", 1)[-1] == callee for other in siblings
    )


class Sources:
    """The native tree as read once per report: text, tokens, includes and the resolved include graph."""

    def __init__(self, workspace: Workspace) -> None:
        self.workspace = workspace
        self.text: dict[str, str] = {}
        self.code: dict[str, str] = {}
        self.includes: dict[str, list[str]] = {}
        native = workspace.native
        for directory, folders, files in os.walk(native):
            folders[:] = [name for name in folders if name not in {"data", "__pycache__", "node_modules"}
                          and not name.startswith(".")]
            for name in files:
                if Path(name).suffix.lower() in NATIVE_SUFFIXES:
                    path = Path(directory) / name
                    relative = path.relative_to(workspace.root).as_posix()
                    text = path.read_text(encoding="utf-8-sig", errors="replace")
                    self.text[relative] = text
                    kept = strip_source(text, keep_strings=True)
                    self.includes[relative] = INCLUDE.findall(kept)
                    self.code[relative] = strip_source(text)
        self.roots = self.include_roots()
        self.edges: dict[str, set[str]] = {path: self.resolve(path) for path in self.includes}
        self.reverse: dict[str, set[str]] = defaultdict(set)
        for path, targets in self.edges.items():
            for target in targets:
                self.reverse[target].add(path)
        self.tokens: dict[str, set[str]] = defaultdict(set)
        for path, code in self.code.items():
            for token in set(IDENTIFIER.findall(code)):
                self.tokens[token].add(path)
        self.definition_cache: dict[str, list[Definition]] = {}

    def include_roots(self) -> list[str]:
        projects = []
        native = self.workspace.native
        if native.is_dir():
            for child in sorted(native.iterdir()):
                if child.is_dir() and child.name not in {"data", "Tools"}:
                    projects.append(child)
            tools = native / "Tools"
            if tools.is_dir():
                projects += sorted(child for child in tools.iterdir() if child.is_dir())
        return [
            (project / suffix).relative_to(self.workspace.root).as_posix()
            for project in projects for suffix in ("", "include", "src")
        ]

    def resolve(self, path: str) -> set[str]:
        found: set[str] = set()
        directory = path.rsplit("/", 1)[0]
        for spelling in self.includes[path]:
            sibling = os.path.normpath(f"{directory}/{spelling}").replace("\\", "/")
            if sibling in self.text:
                found.add(sibling)
                continue
            found |= {f"{root}/{spelling}" for root in self.roots if f"{root}/{spelling}" in self.text}
        return found

    def closure(self, path: str) -> set[str]:
        seen: set[str] = set()
        queue = deque(self.edges.get(path, ()))
        while queue:
            current = queue.popleft()
            if current not in seen:
                seen.add(current)
                queue.extend(self.edges.get(current, ()))
        return seen

    def consumers(self, path: str) -> tuple[set[str], set[str]]:
        direct = set(self.reverse.get(path, ()))
        seen: set[str] = set()
        queue = deque(direct)
        while queue:
            current = queue.popleft()
            if current not in seen:
                seen.add(current)
                queue.extend(self.reverse.get(current, ()))
        return direct, seen - direct

    def definitions(self, path: str) -> list[Definition]:
        if path not in self.definition_cache:
            self.definition_cache[path] = find_definitions(self.text.get(path, ""))
        return self.definition_cache[path]


def compile_settings(workspace: Workspace) -> dict[str, dict]:
    """Actual per-file compile mode from the generated projects; no extension inference."""
    defaults = relaxation_of(xml_root(workspace.props))
    entries: dict[str, dict] = {}
    for directory, folders, files in os.walk(workspace.native):
        folders[:] = [name for name in folders if name != "data" and not name.startswith(".")]
        for name in files:
            if not name.endswith(".vcxproj"):
                continue
            project = Path(directory) / name
            root = xml_root(project)
            project_relaxed = defaults or relaxation_of(root)
            for item in root.iter():
                tag = local(item.tag)
                if tag not in {"ClCompile", "ClInclude"} or "Include" not in item.attrib:
                    continue
                full = project.parent / item.attrib["Include"].replace("\\", "/")
                relative = slash(os.path.relpath(full, workspace.root))
                entry = entries.setdefault(relative, {"compile": "header", "projects": []})
                entry["projects"].append(project.stem)
                if tag == "ClCompile":
                    relaxed = project_relaxed or metadata_relaxed(item)
                    if entry["compile"] != "relaxed":
                        entry["compile"] = "relaxed" if relaxed else "strict"
    return entries


def xml_root(path: Path) -> ET.Element:
    if not path.is_file():
        return ET.Element("Project")
    return ET.fromstring(path.read_text(encoding="utf-8-sig"))


def local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def relaxation_of(root: ET.Element) -> bool:
    for group in root.iter():
        if local(group.tag) == "ItemDefinitionGroup":
            for child in group:
                if local(child.tag) == "ClCompile" and metadata_relaxed(child):
                    return True
    return False


def metadata_relaxed(element: ET.Element) -> bool:
    for child in element:
        tag, value = local(child.tag), (child.text or "").strip()
        if tag == "TreatWarningAsError" and value.lower() == "false":
            return True
        if tag == "WarningLevel" and value not in {"Level4", "EnableAllWarnings"}:
            return True
        if tag == "AdditionalOptions" and "$(VSCopiedCOptions)" in value:
            return True
    return False


class Gates:
    def __init__(self, workspace: Workspace, retiring: dict[str, str] | None) -> None:
        self.workspace = workspace
        self.retiring = RETIRING_NATIVE if retiring is None else retiring
        self.report = Report()
        self.catalog = read_csv(workspace.catalog)
        self.by_id = {row["id"]: row for row in self.catalog}
        self.owned = read_csv(workspace.owned)
        self.owned_by_id = {row["id"]: row for row in self.owned}
        self.promotion = read_csv(workspace.promotion)
        self.verify = read_csv(workspace.verify)
        self.bridges = read_csv(workspace.bridges)
        self.slices = read_csv(workspace.slices)
        self.manifest = {slash(path) for path in json.loads(workspace.manifest.read_text(encoding="utf-8"))}
        self.owned_paths = {slash(row[column]) for row in self.owned for column in ("path", "header") if row[column]}
        baseline = json.loads(workspace.baseline.read_text(encoding="utf-8"))
        self.debt: Counter[str] = Counter()
        for item in baseline["findings"]:
            self.debt[item["path"]] += int(item["count"])
        self.sources = Sources(workspace)
        self.compile = compile_settings(workspace)
        self.test_cases = self.find_test_cases()
        self.bridge_headers = {row["path"] for row in self.bridges if row["kind"] == "header"}
        self.bridge_files = {row["path"] for row in self.bridges}
        self.passing_records: dict[str, set[str]] = defaultdict(set)

    def find_test_cases(self) -> set[str]:
        names = set()
        for path, text in self.sources.text.items():
            if path.startswith("Native/Tests/") and path.endswith(".cpp"):
                for match in TEST_CASE.finditer(strip_source(text, keep_strings=True)):
                    names.add(test_case_name(match.group(1)))
        return names

    def bridge_dependency(self, path: str) -> set[str]:
        return {item for item in self.sources.closure(path)
                if "/Legacy/" in item or item in self.bridge_headers}

    # Ownership (#246) ---------------------------------------------------------------------------------------------

    def ownership(self) -> None:
        report = self.report
        seen: set[str] = set()
        for row in self.owned:
            identifier = row["id"]
            if identifier in seen:
                report.add("ownership", "owned-id-duplicate", identifier, "registered more than once in owned.csv")
            seen.add(identifier)
            ledger_row = self.ledger_row(identifier)
            if ledger_row is None:
                report.add("ownership", "owned-id-missing", identifier, "owned ID is absent from its ledger")
            elif ledger_row.get("final_location", "") != row["path"]:
                report.add("ownership", "owned-location-mismatch", identifier,
                           f"ledger location {ledger_row.get('final_location')!r} differs from {row['path']!r}")
            for column in ("path", "header"):
                relative = slash(row[column])
                if not relative or not (self.workspace.root / relative).is_file():
                    report.add("ownership", "owned-path-missing", identifier, f"{column} {row[column]!r} does not exist")
                if relative in self.manifest:
                    report.add("ownership", "owned-path-generated", identifier,
                               f"{column} {row[column]!r} is listed in copy_manifest.json")
        registered_files = {row["path"] for row in self.owned}
        for row in self.catalog:
            identifier = row["id"]
            status = {column: row.get(column, "") for column in ("cpp", "modernized", "verified")}
            report.row_status[identifier] = status
            report.ownership_states[identifier] = self.ownership_state(row)
            if row["copied"] not in COPIED_VALUES:
                report.add("ownership", "invalid-copied", identifier, f"copied value {row['copied']!r} is not recognized")
            if row["copy"] == "yes" and not row["copied"]:
                report.add("ownership", "invalid-copied", identifier, "port target has a blank copied value")
            if row["copied"] == "retired" and (row["copy"] != "no" or "retired-by:" not in row["notes"]):
                report.add("ownership", "retired-without-evidence", identifier,
                           "a retired row requires copy=no and a retired-by: note")
            if (identifier not in self.owned_by_id and row["copied"] != "retired"
                    and row["final_location"] in registered_files):
                report.add("ownership", "unregistered-row-in-owned-file", identifier,
                           f"{row['final_location']} is owned but the row is neither registered nor retired")
        report.ownership_counts = dict(sorted(Counter(report.ownership_states.values()).items()))
        for column in ("copied", "compiles", "named", "understood", "modernized", "cpp", "verified"):
            report.status_counts[column] = dict(sorted(Counter(row.get(column, "") for row in self.catalog).items()))

    def ledger_row(self, identifier: str) -> dict[str, str] | None:
        if identifier.startswith("F"):
            return self.by_id.get(identifier)
        ledger = self.workspace.data_ledger if identifier.startswith("G") else self.workspace.type_ledger
        return next((row for row in read_csv(ledger) if row["id"] == identifier), None)

    def ownership_state(self, row: dict[str, str]) -> str:
        owned = self.owned_by_id.get(row["id"])
        if owned:
            return "owned-cpp" if owned["path"].lower().endswith(".cpp") else "owned-c"
        if row["copied"] == "retired":
            return "retired"
        return "excluded" if row["copy"] == "no" else "generated"

    # C++ promotion (#247) -----------------------------------------------------------------------------------------

    def measure_steps(self, identifier: str, record: dict[str, str]) -> dict[str, bool]:
        row = self.by_id.get(identifier, {})
        owned = self.owned_by_id.get(identifier)
        path = slash(owned["path"]) if owned else ""
        compile_mode = self.compile.get(path, {}).get("compile")
        strict = path.endswith(".cpp") and compile_mode == "strict"
        expected = f"VS::{row.get('final_name', '')}"
        definitions = self.sources.definitions(path) if path else []
        definition = next((item for item in definitions if item.qualified == expected and not item.c_linkage), None)
        namespace = definition is not None and not is_forwarding_wrapper(definition, definitions)
        return {
            "source_cpp": strict,
            "vs_namespace": namespace,
            "typed_interface": (
                definition is not None and bool(record.get("reviewed"))
                and not LEGACY_SIGNATURE_TYPES.search(definition.signature)
            ),
            "no_bridge": row.get("modernized") == "x" and bool(path) and not self.bridge_dependency(path),
            "strict_clean": strict and self.debt[path] == 0,
            "behavior_evidence": self.behavior_evidence_holds(identifier, record),
        }

    def behavior_evidence_holds(self, identifier: str, record: dict[str, str]) -> bool:
        if not REVISION.match(record.get("reviewed", "")):
            return False
        links = 0
        for reference in split_list(record.get("evidence", "")):
            kind, _, value = reference.partition(":")
            if kind == "test":
                if value not in self.test_cases:
                    return False
                links += 1
            elif kind == "verify":
                if value not in self.passing_records.get(identifier, ()):
                    return False
                links += 1
        return links > 0

    def legacy_symbol_consumers(self, identifier: str) -> set[str]:
        row = self.by_id[identifier]
        names = {c_symbol(row["final_name"])}
        owned = self.owned_by_id.get(identifier)
        if owned:
            names.add(owned["name"])
        return {path for name in names for path in self.sources.tokens.get(name, ())}

    def promotion_gate(self) -> None:
        report = self.report
        records: dict[str, dict[str, str]] = {}
        for record in self.promotion:
            identifier = record["id"]
            if identifier in records:
                report.add("promotion", "promotion-duplicate", identifier, "more than one promotion record")
            records[identifier] = record
        step_counts = Counter({step: 0 for step in STEPS})
        files: dict[str, dict] = {}
        for identifier, record in records.items():
            owned = self.owned_by_id.get(identifier)
            if identifier not in self.by_id or owned is None:
                report.add("promotion", "promotion-not-owned", identifier, "a promotion record requires an owned row")
                continue
            if record["path"] != owned["path"]:
                report.add("promotion", "promotion-path-mismatch", identifier,
                           f"record path {record['path']!r} differs from owned path {owned['path']!r}")
            measured = self.measure_steps(identifier, record)
            file_entry = files.setdefault(record["path"], {"rows": 0, **{step: 0 for step in STEPS}})
            file_entry["rows"] += 1
            verified_steps = 0
            for step in STEPS:
                claim = record[step]
                if claim not in CLAIM_VALUES:
                    report.add("promotion", "invalid-claim", identifier, f"{step} value {claim!r} is not recognized")
                holds = claim == "x" and measured[step]
                if claim == "x" and not measured[step]:
                    report.add("promotion", f"claim-{step}", identifier, f"claimed {step} does not verify")
                if step in MACHINE_STEPS and claim != "x" and measured[step]:
                    report.add("promotion", "promotion-sync-stale", identifier, f"{step} verifies; run gates.py --sync")
                if holds:
                    verified_steps += 1
                    step_counts[step] += 1
                    file_entry[step] += 1
            complete = verified_steps == len(STEPS)
            consumers = self.legacy_symbol_consumers(identifier) if complete else set()
            if consumers:
                report.add("promotion", "legacy-symbol-consumers", identifier,
                           f"callers not adopted: {sorted(consumers)[:5]}")
            report.derived_cpp[identifier] = "x" if complete and not consumers else "wip"
        for row in self.owned:
            if row["kind"] == "function" and row["path"].lower().endswith(".cpp") and row["id"] not in records:
                report.add("promotion", "promotion-record-missing", row["id"],
                           "owned C++ function has no promotion record; run gates.py --sync")
        for row in self.catalog:
            if row["cpp"] not in STATUS_VALUES:
                report.add("promotion", "invalid-cpp", row["id"], f"cpp value {row['cpp']!r} is not recognized")
            derived = report.derived_cpp.get(row["id"], "")
            if row["cpp"] != derived:
                report.add("promotion", "cpp-mismatch", row["id"],
                           f"catalog cpp {row['cpp']!r} differs from derived {derived!r}; run gates.py --sync")
        report.promotion_inventory = {
            "records": len(records), "steps": dict(step_counts), "files": dict(sorted(files.items())),
            "cpp": dict(sorted(Counter(report.derived_cpp.values()).items())),
        }

    # Quality and strict compilation (#248) -------------------------------------------------------------------------

    def source_class(self, path: str) -> str:
        if path in self.retiring or "/Legacy/" in path:
            return "replacement-legacy"
        if path in self.manifest and path not in self.owned_paths:
            return "generated-c"
        return "maintained-c" if path.endswith(".c") else "strict-cpp"

    def quality_gate(self) -> None:
        report = self.report
        owned_functions = Counter(slash(row["path"]) for row in self.owned if row["kind"] == "function")
        for path, entry in sorted(self.compile.items()):
            source_class = self.source_class(path)
            report.source_classes[path] = {
                "class": source_class, "compile": entry["compile"], "projects": sorted(set(entry["projects"])),
                "quality_scope": source_class != "generated-c", "baseline_findings": self.debt[path],
            }
            maintained = source_class == "maintained-c" or (source_class == "replacement-legacy" and owned_functions[path])
            if maintained and entry["compile"] == "relaxed":
                report.relaxation_debt.append({
                    "path": path, "class": source_class, "owned_functions": owned_functions[path],
                    "baseline_findings": self.debt[path],
                })
            if path in self.owned_paths and path.endswith(".cpp") and entry["compile"] == "relaxed":
                report.add("quality", "owned-cpp-relaxed", path, "owned C++ source is compiled with relaxed settings")
        report.class_counts = dict(sorted(Counter(item["class"] for item in report.source_classes.values()).items()))
        for record in self.promotion:
            owned = self.owned_by_id.get(record["id"])
            path = slash(owned["path"]) if owned else slash(record["path"])
            claims = [step for step in STEPS if record[step] == "x"]
            if claims and self.compile.get(path, {}).get("compile") == "relaxed":
                report.add("quality", "promotion-claim-relaxed", record["id"], f"{path} is compiled relaxed")
            if record["strict_clean"] == "x" and self.debt[path]:
                report.add("quality", "strict-clean-with-debt", record["id"],
                           f"{path} has {self.debt[path]} baseline findings")

    # Behavior verification (#249) -----------------------------------------------------------------------------------

    def collect_verification(self) -> None:
        for record in self.verify:
            if record.get("outcome") == "pass" and self.record_resolves(record):
                for identifier in split_list(record["ids"]):
                    self.passing_records[identifier].add(record["record"])

    def record_resolves(self, record: dict[str, str]) -> bool:
        checkable = 0
        for reference in split_list(record["references"]):
            kind, _, value = reference.partition(":")
            if kind == "test":
                if value not in self.test_cases:
                    return False
                checkable += 1
            elif kind in {"replay", "capture"}:
                if not (self.workspace.root / value).exists():
                    return False
                checkable += 1
        return checkable > 0

    def behavior_gate(self) -> None:
        report = self.report
        seen: set[str] = set()
        for record in self.verify:
            name = record["record"]
            if name in seen:
                report.add("behavior", "record-duplicate", name, "record ID used more than once")
            seen.add(name)
            self.check_record(name, record)
        for row in self.catalog:
            marker = row["verified"]
            if marker not in VERIFIED_VALUES:
                report.add("behavior", "invalid-verified", row["id"], f"verified value {marker!r} is not recognized")
            elif marker == "x" and not self.passing_records.get(row["id"]):
                report.add("behavior", "verified-without-record", row["id"],
                           "verified=x has no passing record with resolving references")
        report.behavior = {
            "records": len(self.verify),
            "kinds": dict(sorted(Counter(record["kind"] for record in self.verify).items())),
            "markers": sum(row["verified"] == "x" for row in self.catalog),
            "markers_owned": sum(row["verified"] == "x" and row["id"] in self.owned_by_id for row in self.catalog),
        }

    def check_record(self, name: str, record: dict[str, str]) -> None:
        report = self.report
        if record["kind"] not in VERIFY_KINDS:
            report.add("behavior", "invalid-kind", name, f"kind {record['kind']!r} is not recognized")
        if not REVISION.match(record["revision"]):
            report.add("behavior", "invalid-revision", name, "a commit revision is required")
        configurations = set(split_list(record["configurations"]))
        required = CONFIGURATIONS if record["kind"] in BOTH_CONFIGURATIONS_KINDS else set()
        if configurations - CONFIGURATIONS or not configurations or required - configurations:
            report.add("behavior", "missing-configuration", name,
                       f"{record['kind']} requires {sorted(required) or 'a configuration'}; has {sorted(configurations)}")
        for column, rule in (("limits", "missing-limits"), ("expected", "missing-expected"), ("dirty", "missing-dirty")):
            if not record[column].strip():
                report.add("behavior", rule, name, f"{column} must be recorded")
        if record["outcome"] not in {"pass", "fail", "partial"}:
            report.add("behavior", "invalid-outcome", name, f"outcome {record['outcome']!r} is not recognized")
        for identifier in split_list(record["ids"]):
            if identifier not in self.by_id:
                report.add("behavior", "record-unknown-id", name, f"{identifier} is not in the catalog")
        checkable = 0
        for reference in split_list(record["references"]):
            kind, _, value = reference.partition(":")
            if kind in CHECKABLE_REFERENCES:
                checkable += 1
                exists = value in self.test_cases if kind == "test" else (self.workspace.root / value).exists()
                if not exists:
                    report.add("behavior", "unresolved-reference", name, f"{reference} does not resolve")
            elif kind not in CONTEXT_REFERENCES:
                report.add("behavior", "unresolved-reference", name, f"{reference} has an unknown reference kind")
        if not checkable:
            report.add("behavior", "no-checkable-reference", name, "needs a test, replay or capture reference")

    # Compatibility retirement (#250) -------------------------------------------------------------------------------

    def consumer_groups(self, paths: set[str]) -> dict[str, list[str]]:
        groups: dict[str, list[str]] = {"owned": [], "generated": [], "other": []}
        for path in sorted(paths):
            if path in self.bridge_files or "/Legacy/" in path:
                continue
            if path in self.owned_paths:
                groups["owned"].append(path)
            elif path in self.manifest:
                groups["generated"].append(path)
            else:
                groups["other"].append(path)
        return groups

    def retirement_gate(self) -> None:
        report = self.report
        by_ec: dict[str, list[dict[str, str]]] = defaultdict(list)
        for bridge in self.bridges:
            if not re.fullmatch(r"EC-\d\d", bridge["ec"]) or bridge["kind"] not in {"header", "source"}:
                report.add("retirement", "invalid-bridge-entry", bridge["path"], f"{bridge['ec']}/{bridge['kind']}")
            if not (self.workspace.root / bridge["path"]).is_file():
                report.add("retirement", "bridge-path-missing", bridge["path"],
                           "listed bridge does not exist; update EC_BRIDGES.csv for the moved or renamed file")
            by_ec[bridge["ec"]].append(bridge)
        for ec, entries in sorted(by_ec.items()):
            direct: set[str] = set()
            transitive: set[str] = set()
            for bridge in entries:
                if bridge["kind"] == "header":
                    near, far = self.sources.consumers(bridge["path"])
                    direct |= near
                    transitive |= far
            near_groups = self.consumer_groups(direct)
            far_groups = self.consumer_groups(transitive - direct)
            report.bridge_consumers[ec] = {
                "bridges": sorted(bridge["path"] for bridge in entries),
                "direct": near_groups, "transitive": far_groups,
                "direct_counts": {key: len(value) for key, value in near_groups.items()},
                "transitive_counts": {key: len(value) for key, value in far_groups.items()},
            }
        for path in sorted(self.sources.text):
            if "/Legacy/" in path and path.endswith(".h"):
                near, _ = self.sources.consumers(path)
                report.legacy_consumers[path] = self.consumer_groups(near)
        for row in self.catalog:
            marker = row["modernized"]
            identifier = row["id"]
            if marker not in STATUS_VALUES:
                report.add("retirement", "invalid-modernized", identifier, f"modernized value {marker!r} is not recognized")
                continue
            if marker and identifier not in self.owned_by_id:
                report.add("retirement", "modernized-not-owned", identifier, f"modernized={marker} requires ownership")
            elif marker == "x":
                dependency = self.bridge_dependency(slash(self.owned_by_id[identifier]["path"]))
                if dependency:
                    report.add("retirement", "modernized-with-bridge", identifier,
                               f"still reaches {sorted(dependency)[:3]}")
        for record in self.slices:
            self.check_slice(record)

    def old_bridge_consumers(self, reference: str) -> set[str]:
        kind, _, value = reference.partition(":")
        if kind == "symbol":
            return set(self.sources.tokens.get(value, ()))
        if kind == "header":
            return {path for path, spellings in self.sources.includes.items() if value in spellings}
        return set()

    def check_slice(self, record: dict[str, str]) -> None:
        report = self.report
        name = record["slice"]
        for identifier in split_list(record["ids"]):
            if identifier not in self.owned_by_id:
                report.add("retirement", "slice-not-owned", name, f"{identifier} is not owned")
        consumers: set[str] = set()
        for reference in split_list(record["old_bridges"]):
            if reference.partition(":")[0] not in {"symbol", "header"}:
                report.add("retirement", "slice-invalid-bridge", name, f"{reference} must be symbol: or header:")
            consumers |= self.old_bridge_consumers(reference)
        measured = len(consumers)
        if str(measured) != record["after"]:
            report.add("retirement", "slice-consumer-mismatch", name,
                       f"recorded after={record['after']} but measured {measured}: {sorted(consumers)[:5]}")
        report.slices.append({
            "slice": name, "ids": split_list(record["ids"]), "ec": record["ec"],
            "old_bridges": split_list(record["old_bridges"]), "before": int(record["before"]), "after": measured,
            "before_revision": record["before_revision"], "consumers": sorted(consumers),
        })

    # Summary ---------------------------------------------------------------------------------------------------------

    def summary_block(self) -> str:
        report = self.report
        states = report.ownership_counts
        owned = [row for row in self.owned if row["kind"] == "function"]
        inventory = report.promotion_inventory
        lines = [
            SUMMARY_BEGIN, "",
            "| Count | Ownership state |", "| ---: | --- |",
            f"| {len(owned)} | owned functions |",
            f"| {states.get('owned-cpp', 0)} | owned functions in C++ sources |",
            f"| {states.get('owned-c', 0)} | owned functions in maintained C sources |",
            f"| {states.get('generated', 0)} | generated function rows |",
            f"| {states.get('retired', 0)} | retired function rows |",
            f"| {states.get('excluded', 0)} | excluded function rows |",
            "", "| Column | `x` | Other non-blank | Blank |", "| --- | ---: | ---: | ---: |",
        ]
        for column, counts in report.status_counts.items():
            other = sum(count for value, count in counts.items() if value not in {"", "x"})
            names = ", ".join(f"`{value}`" for value in counts if value not in {"", "x"})
            lines.append(f"| `{column}` | {counts.get('x', 0):,} | {other:,}{f' ({names})' if names else ''} "
                         f"| {counts.get('', 0):,} |")
        lines += ["", "| §8.2 promotion step | Verified records |", "| --- | ---: |"]
        lines += [f"| `{step}` | {count} |" for step, count in inventory["steps"].items()]
        derived = inventory["cpp"]
        lines += [
            "", f"Promotion records: {inventory['records']}; derived `cpp=x`: {derived.get('x', 0)}, "
            f"`cpp=wip`: {derived.get('wip', 0)}. Verification records: {report.behavior['records']}; "
            f"`verified=x` markers: {report.behavior['markers']}.", "", SUMMARY_END,
        ]
        return "\n".join(lines)

    def check_summary(self) -> None:
        text = self.workspace.summary.read_text(encoding="utf-8") if self.workspace.summary.is_file() else ""
        if self.summary_block() not in text.replace("\r\n", "\n"):
            self.report.add("ownership", "summary-stale", "SUMMARY.md", "generated block differs; run gates.py --sync")

    def run(self) -> Report:
        self.collect_verification()
        self.ownership()
        self.promotion_gate()
        self.quality_gate()
        self.behavior_gate()
        self.retirement_gate()
        self.check_summary()
        return self.report


def test_case_name(literals: str) -> str:
    joined = "".join(STRING_LITERAL.findall(literals))
    return joined.replace('\\"', '"').replace("\\\\", "\\")


def build_report(workspace: Workspace, retiring: dict[str, str] | None = None) -> Report:
    return Gates(workspace, retiring).run()


def csv_line_terminator(path: Path) -> str:
    with path.open("rb") as stream:
        return "\r\n" if b"\r\n" in stream.readline() else "\n"


def write_rows(path: Path, rows: list[list[str]], terminator: str) -> None:
    buffer = io.StringIO(newline="")
    csv.writer(buffer, lineterminator=terminator).writerows(rows)
    data = buffer.getvalue().encode("utf-8")
    if not path.is_file() or path.read_bytes() != data:
        path.write_bytes(data)


def sync(workspace: Workspace) -> None:
    """Refresh tool-owned facts only: machine step columns, record paths, derived cpp and the summary block."""
    gates = Gates(workspace, None)
    gates.collect_verification()
    records = {row["id"]: dict(row) for row in gates.promotion}
    for owned in gates.owned:
        if owned["kind"] == "function" and owned["path"].lower().endswith(".cpp") and owned["id"] in gates.by_id:
            records.setdefault(owned["id"], {name: "" for name in PROMOTION_FIELDS} | {"id": owned["id"]})
    for identifier, record in records.items():
        owned = gates.owned_by_id.get(identifier)
        if owned:
            record["path"] = owned["path"]
        measured = gates.measure_steps(identifier, record)
        for step in MACHINE_STEPS:
            record[step] = "x" if measured[step] else ""
    ordered = [records[identifier] for identifier in sorted(records)]
    write_rows(workspace.promotion, [PROMOTION_FIELDS, *[[row[name] for name in PROMOTION_FIELDS] for row in ordered]], "\n")

    gates = Gates(workspace, None)
    gates.collect_verification()
    gates.ownership()
    gates.promotion_gate()
    derived = gates.report.derived_cpp
    terminator = csv_line_terminator(workspace.catalog)
    with workspace.catalog.open(encoding="utf-8-sig", newline="") as stream:
        table = list(csv.reader(stream))
    id_column, cpp_column = table[0].index("id"), table[0].index("cpp")
    for row in table[1:]:
        row[cpp_column] = derived.get(row[id_column], "")
    write_rows(workspace.catalog, table, terminator)
    write_summary(workspace)


def write_summary(workspace: Workspace) -> None:
    gates = Gates(workspace, None)
    gates.collect_verification()
    gates.ownership()
    gates.promotion_gate()
    gates.quality_gate()
    gates.behavior_gate()
    block = gates.summary_block()
    path = workspace.summary
    raw = path.read_bytes().decode("utf-8") if path.is_file() else ""
    terminator = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    pattern = re.compile(re.escape(SUMMARY_BEGIN.split(" (")[0]) + r".*?" + re.escape(SUMMARY_END), re.S)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    path.write_bytes(text.replace("\n", terminator).encode("utf-8"))


def markdown(report: Report) -> str:
    lines = ["# Native-port gate report", "",
             "Each section is a separate gate. A stored ledger state is not a fresh build, test or gameplay run.", ""]
    lines += ["## Ownership", ""] + [f"- {state}: {count}" for state, count in report.ownership_counts.items()]
    inventory = report.promotion_inventory
    lines += ["", "## C++ promotion", "", f"- records: {inventory['records']}; derived cpp: {inventory['cpp']}"]
    lines += [f"- {step}: {count}" for step, count in inventory["steps"].items()]
    lines += ["", "| File | Rows | " + " | ".join(STEPS) + " |", "| --- | ---: |" + " ---: |" * len(STEPS)]
    for path, entry in inventory["files"].items():
        lines.append(f"| {path} | {entry['rows']} | " + " | ".join(str(entry[step]) for step in STEPS) + " |")
    lines += ["", "## Quality and compilation", ""]
    lines += [f"- {name}: {count} files" for name, count in report.class_counts.items()]
    lines += ["", "Maintained C compiled with relaxed settings:", "", "| File | Owned functions | Baseline findings |",
              "| --- | ---: | ---: |"]
    lines += [f"| {item['path']} | {item['owned_functions']} | {item['baseline_findings']} |"
              for item in report.relaxation_debt]
    lines += ["", "## Behavior verification", "", f"- {json.dumps(report.behavior)}", "",
              "## Compatibility retirement", "",
              "| EC | Direct owned | Direct generated | Direct other | Indirect owned | Indirect generated | Indirect other |",
              "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for ec, entry in report.bridge_consumers.items():
        near, far = entry["direct_counts"], entry["transitive_counts"]
        lines.append(f"| {ec} | {near['owned']} | {near['generated']} | {near['other']} | "
                     f"{far['owned']} | {far['generated']} | {far['other']} |")
    lines += ["", "Slices:", ""]
    lines += [f"- {item['slice']} ({item['ec']}): {item['before']} old-bridge consumers at "
              f"{item['before_revision'][:8]}, {item['after']} now; rows {', '.join(item['ids'])}"
              for item in report.slices]
    lines += ["", f"## Violations: {len(report.issues)}", ""]
    lines += [f"- [{item.gate}] {item.rule} {item.subject}: {item.message}" for item in report.issues]
    return "\n".join(lines) + "\n"


def write_reports(report: Report, directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    payload = asdict(report)
    (directory / "gates.json").write_text(json.dumps(payload, indent=1), encoding="utf-8")
    (directory / "gates.md").write_text(markdown(report), encoding="utf-8")
    with (directory / "gates-rows.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(["id", "ownership", "cpp", "derived_cpp", "modernized", "verified"])
        for identifier, state in report.ownership_states.items():
            status = report.row_status[identifier]
            writer.writerow([identifier, state, status["cpp"], report.derived_cpp.get(identifier, ""),
                             status["modernized"], status["verified"]])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 on any gate violation")
    parser.add_argument("--sync", action="store_true", help="refresh machine-checked columns and the summary block")
    arguments = parser.parse_args()
    workspace = Workspace()
    if arguments.sync:
        sync(workspace)
    report = build_report(workspace)
    write_reports(report, workspace.root / "build" / "quality")
    for item in report.issues:
        print(f"[{item.gate}] {item.rule} {item.subject}: {item.message}")
    inventory = report.promotion_inventory
    print(f"ownership {report.ownership_counts}")
    print(f"promotion {inventory['cpp']} steps {inventory['steps']}")
    print(f"quality {report.class_counts}; {len(report.relaxation_debt)} relaxed maintained C files")
    print(f"behavior {report.behavior}")
    print(f"retirement {[(ec, entry['direct_counts']) for ec, entry in report.bridge_consumers.items()]}")
    print(f"{len(report.issues)} violations; reports in build/quality")
    return 1 if arguments.check and report.issues else 0


