// Not constexpr: Locate calls it for a path missing from kFiles, which stops
// compilation with this function's name in the diagnostic.
inline void DiscFileNotInLayout() noexcept {}

// The extent of the disc file at `path` (for example "BATTLE/BATTLE.PRG").
// Evaluated at compile time: a path not in kFiles does not compile.
consteval FileExtent Locate(std::string_view path) noexcept {
  const auto entry =
      std::ranges::lower_bound(kFiles, path, {}, &FileEntry::path);
  if (entry == kFiles.end() || entry->path != path) {
    DiscFileNotInLayout();
  }
  return entry->extent;
}

// The extent as another {lba, size} record, such as Content::DiscFile.
template <typename Record>
consteval Record LocateAs(std::string_view path) noexcept {
  const FileExtent file = Locate(path);
  return Record{file.lba, file.size};
}

