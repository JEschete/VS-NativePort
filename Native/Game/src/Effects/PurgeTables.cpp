// An effect file's sectors past E000.P, the first effect file, and its
// sector-rounded size: what EFFPURGE.BIN's FBC, FBT, P and PLG macros spell.
// decomp: src/EFFECT/EFFPURGE.BIN/0.c:158
consteval EffectFileExtent EffectFile(std::string_view path) noexcept {
  constexpr std::int32_t kLimit = std::numeric_limits<std::uint16_t>::max();
  const Content::disc::FileExtent file = Content::disc::Locate(path);
  const std::int32_t offset =
      file.lba - Content::disc::Locate("EFFECT/E000.P").lba;
  if (offset < 0 || offset > kLimit || file.size > kLimit) {
    EffectFileOutOfRange();
  }
  return {static_cast<std::uint16_t>(offset),
          static_cast<std::uint16_t>(file.size)};
}

