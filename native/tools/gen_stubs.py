#!/usr/bin/env python3
"""Generate the Phase 0 native stub layer.

Scans the compiled native objects for undefined symbols and emits a C file
defining each one, so the native target links before any real platform layer
exists. Symbols provided by host libc, or by the native platform layer itself,
are deliberately left alone so they bind to the real implementation.

Usage: gen_stubs.py <objdir> <out.c> <libc.so> [asmroot]

A missing symbol is stubbed as a FUNCTION only if the disassembly defines it
with `glabel` (i.e. it lives in a code section); otherwise it is emitted as a
writable data blob. Getting this wrong is not cosmetic: a data symbol stubbed
as a function lands in read-only .text, so any write to it segfaults.
"""
import subprocess, sys, pathlib, re

PLATFORM_PROVIDED = {"_psx_scratchpad", "_native_unimplemented", "main"}

# Symbols the retail build defsym's onto the 1KB scratchpad at 0x1F800000, so
# they ALIAS that region rather than being distinct objects (see the
# --defsym lines in config/*/Makefile). The native build reproduces this with
# matching --defsym flags in Makefile.native, so these must NOT be emitted as
# separate blobs here -- doing so gives each its own memory and the three views
# of the scratchpad (D_1F800000[i], *(void**)0x1F800000, _camera.x) diverge,
# which strands the per-frame render pointers as null.
SCRATCHPAD_ALIASES = {"D_1F800000", "_camera"}
NL = chr(10)


def nm(args):
    return subprocess.run(["nm"] + args, capture_output=True, text=True).stdout


def glabel_functions(asmroot):
    """Every name defined as a function (glabel/alabel) in the disassembly."""
    fns = set()
    if not asmroot or not pathlib.Path(asmroot).exists():
        return fns
    out = subprocess.run(
        ["grep", "-rhoE", r"\b[ag]label [A-Za-z_][A-Za-z0-9_]*", asmroot],
        capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 2:
            fns.add(parts[1])
    return fns


def main(objdir, out, libc):
    objs = sorted(str(p) for p in pathlib.Path(objdir).glob("*.o")
                  if "plat_stubs" not in p.name)
    undef, defined = set(), set()
    for line in nm(["-u"] + objs).splitlines():
        f = line.split()
        if len(f) >= 2 and f[0] == "U":
            undef.add(f[1])
    for line in nm(objs).splitlines():
        f = line.split()
        # Only GLOBAL definitions satisfy an external reference. nm uses
        # uppercase for global and lowercase for local/static, so a lowercase
        # entry (e.g. "b _score", a static in some other TU) must NOT count as
        # defined -- otherwise the symbol is skipped here and the link fails.
        if len(f) == 3 and f[1].isupper() and f[1] != "U":
            defined.add(f[2])
    libcsyms = set()
    for line in nm(["-D", "--defined-only", libc]).splitlines():
        f = line.split()
        if f:
            libcsyms.add(f[-1].split("@")[0])

    asmroot = sys.argv[4] if len(sys.argv) > 4 else "build/src"
    functions_in_asm = glabel_functions(asmroot)

    syms = sorted(s for s in undef - defined
                  if not s.startswith("__")
                  and s not in libcsyms
                  and s not in PLATFORM_PROVIDED
                  and s not in SCRATCHPAD_ALIASES)

    # A symbol is a function iff the disassembly defines it as code (glabel).
    # D_* that are also glabel'd (rare) still count as functions. Everything
    # else is data -> a writable blob, so reads/writes are safe.
    funcs = [s for s in syms if s in functions_in_asm]
    data = [s for s in syms if s not in functions_in_asm]

    lines = [
        "/* AUTO-GENERATED by native/tools/gen_stubs.py -- do not hand-edit. */",
        "extern void _native_unimplemented(const char* name);",
        "",
        "/* ---- data symbols (%d): writable zero blobs ---- */" % len(data),
    ]
    # 4KB is generous headroom for the game structs/arrays these back; under-
    # sizing would let indexed writes clobber the next blob.
    lines += ["unsigned char %s[4096] __attribute__((aligned(16)));" % s for s in data]
    lines += ["", "/* ---- function stubs (%d) ---- */" % len(funcs)]
    lines += ["void %s(void) { _native_unimplemented(\"%s\"); }" % (s, s) for s in funcs]
    pathlib.Path(out).write_text(NL.join(lines) + NL)
    print("  GEN      %s (%d functions, %d data)" % (out, len(funcs), len(data)))


if __name__ == "__main__":
    main(*sys.argv[1:5])
