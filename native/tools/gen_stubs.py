#!/usr/bin/env python3
"""Generate the Phase 0 native stub layer.

Scans the compiled native objects for undefined symbols and emits a C file
defining each one, so the native target links before any real platform layer
exists. Symbols provided by host libc, or by the native platform layer itself,
are deliberately left alone so they bind to the real implementation.

Usage: gen_stubs.py <objdir> <out.c> <libc.so>
"""
import subprocess, sys, pathlib

PLATFORM_PROVIDED = {"_psx_scratchpad", "_native_unimplemented", "main"}
NL = chr(10)


def nm(args):
    return subprocess.run(["nm"] + args, capture_output=True, text=True).stdout


def main(objdir, out, libc):
    objs = sorted(str(p) for p in pathlib.Path(objdir).glob("*.o")
                  if "plat_stubs" not in p.name)
    undef, defined = set(), set()
    for line in nm(["-u"] + objs).splitlines():
        f = line.split()
        if len(f) >= 2 and f[0] == "U":
            undef.add(f[1])
    for line in nm(objs).splitlines():
        f = line.split()
        if len(f) == 3 and f[1] not in ("U", "u"):
            defined.add(f[2])
    libcsyms = set()
    for line in nm(["-D", "--defined-only", libc]).splitlines():
        f = line.split()
        if f:
            libcsyms.add(f[-1].split("@")[0])

    syms = sorted(s for s in undef - defined
                  if not s.startswith("__")
                  and s not in libcsyms
                  and s not in PLATFORM_PROVIDED)
    funcs = [s for s in syms if not s.startswith("D_")]
    data = [s for s in syms if s.startswith("D_")]

    lines = [
        "/* AUTO-GENERATED by native/tools/gen_stubs.py -- do not hand-edit. */",
        "extern void _native_unimplemented(const char* name);",
        "",
        "/* ---- data symbols (%d) ---- */" % len(data),
    ]
    lines += ["unsigned char %s[256] __attribute__((aligned(16)));" % s for s in data]
    lines += ["", "/* ---- function stubs (%d) ---- */" % len(funcs)]
    lines += ["void %s(void) { _native_unimplemented(\"%s\"); }" % (s, s) for s in funcs]
    pathlib.Path(out).write_text(NL.join(lines) + NL)
    print("  GEN      %s (%d functions, %d data)" % (out, len(funcs), len(data)))


if __name__ == "__main__":
    main(*sys.argv[1:4])
