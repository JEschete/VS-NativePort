"""Generate native/platform/assets.c -- the overlays' binary assets.

splat extracts things like the compressed title background and the font tables
as standalone objects under build/assets/, and the PSX build links them into the
overlay that uses them (see config/TITLE/TITLE.PRG/Makefile). The native build
links every overlay together, so it needs the same bytes -- otherwise the symbol
falls through to the stub generator as a zeroed blob and, for example,
_copyTitleBgData decompresses garbage and runs off the end of its buffer.

The payload is emitted with `.incbin` rather than as a C array: 4MB of data as
hex initialisers would be ~25MB of source for no benefit.

Run via `make -f Makefile.native assets`.
"""

import os
import subprocess
import sys

OBJCOPY = os.environ.get("MIPS_OBJCOPY", "mipsel-linux-gnu-objcopy")


def find_assets(root):
    out = []
    base = os.path.join(root, "build/assets")
    for dirpath, _, files in os.walk(base):
        for fn in sorted(files):
            if fn.endswith(".o"):
                out.append(os.path.join(dirpath, fn))
    return sorted(out)


def symbol_of(path):
    """_titleScreenBg.rgba16Compressed.img.o -> _titleScreenBg"""
    return os.path.basename(path).split(".")[0]


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out_c = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "native/platform/assets.c")
    bindir = os.path.join(root, "native/build/assets")
    os.makedirs(bindir, exist_ok=True)

    seen, entries = {}, []
    for obj in find_assets(root):
        sym = symbol_of(obj)
        if sym in seen:
            print("  SKIP  %s (already provided by %s)" % (sym, seen[sym]))
            continue
        raw = os.path.join(bindir, sym + ".bin")
        try:
            subprocess.check_call([OBJCOPY, "-O", "binary", obj, raw])
        except (OSError, subprocess.CalledProcessError) as e:
            print("  FAIL  %s (%s)" % (sym, e))
            continue
        size = os.path.getsize(raw)
        if size == 0:
            print("  SKIP  %s (empty)" % sym)
            continue
        seen[sym] = obj
        entries.append((sym, os.path.relpath(raw, root), size))
        print("  ASSET %-24s %8d bytes" % (sym, size))

    with open(out_c, "w") as f:
        f.write("/* AUTO-GENERATED by native/tools/gen_assets.py -- do not hand-edit.\n"
                " *\n"
                " * Binary assets extracted from the overlays by splat. See that script.\n"
                " * Emitted with .incbin so the bytes are exact and compilation stays fast. */\n\n")
        for sym, path, size in entries:
            f.write("/* %d bytes */\n" % size)
            f.write("__asm__(\n")
            f.write("    \".section .rodata\\n\"\n")
            f.write("    \".balign 16\\n\"\n")
            f.write("    \".globl %s\\n\"\n" % sym)
            f.write("    \"%s:\\n\"\n" % sym)
            f.write("    \".incbin \\\"%s\\\"\\n\"\n" % path)
            f.write("    \".size %s, %d\\n\"\n" % (sym, size))
            f.write("    \".text\\n\");\n\n")
        f.write("const int psx_asset_count = %d;\n" % len(entries))

    print("assets: %d emitted" % len(entries))


if __name__ == "__main__":
    main()
