"""Generate native/platform/disc_index.c -- the LBA -> extracted-file map.

The game asks the CD driver for data by LBA, because that is what a PlayStation
does. The port should NOT need the disc image at runtime, so this builds a table
mapping each LBA range back to the corresponding file in the extracted `data/`
tree. libds then serves reads out of ordinary files.

Sources, both already in the repo and both generated from the user's own disc by
the normal build:
  - build/src/include/lbas.h   VS_<NAME>_LBA / VS_<NAME>_SIZE for every file
  - config/SLUS-01040.xml      the mkpsxiso layout: the real directory tree

Run via `make -f Makefile.native discindex`.
"""

import os
import re
import sys
import xml.etree.ElementTree as ET

SECTOR = 2048


def parse_lbas(path):
    lba, size = {}, {}
    pat = re.compile(r"#define\s+VS_(\w+)_(LBA|SIZE)\s+(\d+)")
    with open(path) as f:
        for line in f:
            m = pat.match(line.strip())
            if not m:
                continue
            name, kind, val = m.group(1), m.group(2), int(m.group(3))
            (lba if kind == "LBA" else size)[name] = val
    return lba, size


def macro_name(filename):
    """VS_<FILENAME with . and - replaced by _>, uppercased."""
    return filename.upper().replace(".", "_").replace("-", "_")


def walk(node, prefix, out):
    for child in node:
        if child.tag == "file":
            name = child.get("name")
            out.append((prefix + name if prefix else name, name))
        elif child.tag == "dir":
            walk(child, prefix + child.get("name") + "/", out)


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    lbas_h = os.path.join(root, "build/src/include/lbas.h")
    iso_xml = os.path.join(root, "config/SLUS-01040.xml")
    out_c = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "native/platform/disc_index.c")

    if not os.path.exists(lbas_h):
        sys.exit("missing %s -- run the PSX build first (it generates lbas.h)" % lbas_h)

    lba, size = parse_lbas(lbas_h)
    tree = ET.parse(iso_xml)
    files = []
    for dt in tree.iter("directory_tree"):
        walk(dt, "", files)

    entries, missing, mismatched = [], [], []
    for relpath, filename in files:
        key = macro_name(filename)
        if key not in lba:
            missing.append(relpath)
            continue
        disk = os.path.join(root, "data", relpath)
        actual = os.path.getsize(disk) if os.path.exists(disk) else -1
        declared = size.get(key, -1)
        nbytes = actual if actual >= 0 else declared
        sectors = (nbytes + SECTOR - 1) // SECTOR
        # lbas.h SIZE is the sector-padded length the file occupies on the disc,
        # so it is normally larger than the file itself. Only a difference in
        # SECTOR count means the extracted file disagrees with the layout.
        if actual >= 0 and declared >= 0:
            if sectors != (declared + SECTOR - 1) // SECTOR:
                mismatched.append((relpath, declared, actual))
        entries.append((lba[key], sectors, relpath))

    entries.sort()
    # Drop entries that overlap a previous one (defensive: the table must be a
    # clean partition for the binary search in libds to be meaningful).
    clean = []
    for e in entries:
        if clean and e[0] < clean[-1][0] + clean[-1][1]:
            continue
        clean.append(e)

    with open(out_c, "w") as f:
        f.write("/* AUTO-GENERATED by native/tools/gen_disc_index.py"
                " -- do not hand-edit.\n *\n"
                " * Maps disc LBA ranges to files in the extracted data/ tree so the\n"
                " * native port reads assets from ordinary files instead of needing the\n"
                " * disc image at runtime. See that script for how it is derived. */\n")
        f.write("#include \"disc_index.h\"\n\n")
        f.write("const psx_disc_entry psx_disc_index[] = {\n")
        for l, s, p in clean:
            f.write('    { %d, %d, "%s" },\n' % (l, s, p))
        f.write("};\n\n")
        f.write("const int psx_disc_index_count ="
                " (int)(sizeof psx_disc_index / sizeof psx_disc_index[0]);\n")

    print("disc index: %d files, %d sectors covered" %
          (len(clean), sum(s for _, s, _ in clean)))
    if missing:
        print("  no LBA macro for %d file(s), e.g. %s" % (len(missing), missing[:3]))
    if mismatched:
        print("  size mismatch on %d file(s), e.g. %s" % (len(mismatched), mismatched[:3]))
    if len(entries) != len(clean):
        print("  dropped %d overlapping entries" % (len(entries) - len(clean)))


if __name__ == "__main__":
    main()
